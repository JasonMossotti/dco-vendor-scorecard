const { JSDOM, VirtualConsole } = require("jsdom");
const fs = require("fs");
const html = fs.readFileSync(process.argv[2], "utf8");
const errors = [];
const dom = new JSDOM(html, { runScripts: "dangerously", url: "https://example.test/availability/", virtualConsole: new VirtualConsole().on("jsdomError", e => errors.push(String(e))) });
const w = dom.window, d = w.document;
const t = () => d.getElementById("doc").textContent;
const ok = (c, m) => { if (!c) { console.log("FAIL:", m); process.exitCode = 1; } else console.log("ok:", m); };
const D = JSON.parse(d.getElementById("data").textContent);
const hover = (el, type) => el.dispatchEvent(new w.MouseEvent(type, { bubbles: true, clientX: 50, clientY: 50 }));
const visible = () => [...d.querySelectorAll("#tickets tbody tr")].filter(tr => !tr.hidden);

ok(errors.length === 0, "no script errors " + errors.join(";"));
ok(t().includes("Availability and repair turnaround") && d.querySelectorAll(".tile").length === 4 + D.spares.kms.length, "title, four headline tiles, and a tile per spares Key Measurement");
ok(t().includes(D.sched.pct.toFixed(3) + "%") && t().includes(D.csl01.actual.toFixed(3) + "%"), "scheduler and CSL-01 availability shown");
ok(D.owners.every(o => t().includes(o.owner)) && t().includes("1,524.9"), "every owner and the contracts' total");
ok(d.querySelectorAll("#bridge tr").length === D.bridge.rows.length + 1 && D.bridge.closes && !t().includes("does not close"), "the bridge lists every step and closes");
ok(d.querySelectorAll("#c1 .hit").length === D.days.length, "a hover target per day");
hover(d.querySelector("#c1 .hit[data-i='15']"), "mousemove");
const tip = d.querySelector("#c1 .tip");
ok(tip.style.display === "block" && tip.textContent.includes("Landlord") && tip.textContent.includes("Hall A available"), "the outage day shows the Landlord's share and each hall's availability");
hover(d.querySelector("#c1 .hit[data-i='15']"), "mouseleave");
ok(tip.style.display === "none", "and hides it after");
const tb = d.getElementById("tbl1");
tb.click();
ok(!d.getElementById("t1").hidden && d.querySelectorAll("#t1 tr").length === D.days.length + 1, "the table view lists every day");
ok(d.querySelectorAll("#stages tr").length === D.stage_summary.length + 1 && D.stages.every(s => t().includes(s.short)), "a stage row per cause, every stage named");
ok(visible().length === D.tickets.length && d.getElementById("fcount").textContent.includes(`${D.tickets.length} of ${D.tickets.length}`), "every ticket listed");
const fc = d.getElementById("fcause");
fc.value = "switch_tray"; fc.dispatchEvent(new w.Event("change"));
ok(visible().length === D.tickets.filter(x => x.category === "switch_tray").length && visible()[0].textContent.includes("NVLink switch tray"), "filter by cause");
fc.value = ""; fc.dispatchEvent(new w.Event("change"));
const ff = d.getElementById("fflag");
ff.checked = true; ff.dispatchEvent(new w.Event("change"));
const flagged = visible().map(tr => tr.cells[0].textContent);
ok(flagged.includes("INC3100748") && flagged.includes("INC3100357") && flagged.length < D.tickets.length, "only tickets with a gap, a finding, or a missing record");
const r748 = visible().find(tr => tr.cells[0].textContent === "INC3100748");
ok(r748.textContent.includes("No validation record") && r748.textContent.includes("F-008"), "a missing stage says so and names its finding");
const r357 = visible().find(tr => tr.cells[0].textContent === "INC3100357");
ok(r357.cells[7].textContent.startsWith("+1 h 49 min"), "the clock-shifted ticket shows its gap");
ok(d.querySelectorAll("#spares tr").length === D.spares.rows.length + 1 && d.querySelectorAll("#spares svg.spark").length === D.spares.rows.length, "a row and a sparkline per spares class");
ok(d.querySelector("#spares .flag.bad") && t().includes("Compute tray: lowest 1, minimum 6"), "the class below its minimum is flagged");
ok(t().includes("not that anyone misled"), "a difference is framed as records that do not reconcile");
ok(!/Lane Mbeki|Kendall Patel|Cameron Chen/.test(d.body.textContent), "no technician is named");
ok(errors.length === 0, "still no script errors " + errors.join(";"));
