#!/usr/bin/env python3
"""PM coverage: every Landlord device that needs preventive maintenance, its last and next PM, and the gaps
(reports/pm_coverage.md).

Usage:
    python scripts/render_pm.py                  # write reports/pm_coverage.md
    python scripts/render_pm.py --check          # fail if the report is stale
    python scripts/render_pm.py --robustness 60  # 60 forward schedules and opening registers, scored

The Operations page's PM coverage view (/ops/#pm) is built from prepare() by scripts/render_ops.py.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import pm_coverage as PC  # noqa: E402
from scorecard.synthetic.change_calendar import ForwardSchedule  # noqa: E402
from scorecard.synthetic.pm_coverage import OpeningRegister  # noqa: E402

LAYER = ROOT / "data" / "pm_coverage"
OUT = ROOT / "reports" / "pm_coverage.md"


def prepare() -> dict:
    """Everything the report and the page show (scorecard.pm_coverage.page_data)."""
    return PC.page_data()


def _md(s: str | None) -> str:
    return PC._md(s) if s else ""


def markdown(f: dict) -> str:
    c, S = f["count"], f["status_names"]
    out = ["# PM coverage", "",
           f"Site AUS-1 (synthetic), as of {f['as_of']}, looking ahead to {f['horizon']} (Hall C first compute). Generated by "
           "`scripts/render_pm.py` from `config/pm_program.yaml`, the PM records, `data/pm_coverage/`, and "
           "`data/calendar/schedule.json`; do not edit by hand.", "",
           "Every Landlord device the maintenance schedule covers in Halls A and B and the site-wide plant (Hall C joins at "
           "handover), each task's last completion, its next due date, and whether it is booked on the maintenance calendar "
           "on or before its grace limit.", "",
           "## Result", "",
           f"{f['devices']} devices and rooms, {len(f['lines'])} device-task lines, {f['records']} PM records read, {f['bookings']} "
           "PM bookings in the forward schedule.", "",
           "| Status | Lines |", "|---|---:|"]
    for k, name in S.items():
        out.append(f"| {name} | {c[k]} |")
    out += ["", "## By task", "", "| System | Task | Interval | Lines | Status |", "|---|---|---|---:|---|"]
    for t in f["tasks"]:
        st = ", ".join(f"{S[k]} {n}" for k, n in t["status"].items())
        out.append(f"| {t['system']} | {t['task']}{'' if t['in_schedule'] else ' (added by the coverage clause)'} | "
                   f"{t['interval'].replace('_', ' ')} | {t['lines']} | {st} |")
    out += ["", "## Findings", "",
            "A finding means the PM records and the bookings do not reconcile with the schedule; it starts the coverage procedure "
            "(Landlord SLA section 11.1), not a judgment of anyone, and changes no service level.", "",
            "| ID | Kind | Device | Task | Last done | Due | Grace ends | Booked | What |", "|---|---|---|---|---|---|---|---|---|"]
    for x in f["findings"]:
        dev = ", ".join(x["units"]) if len(x["units"]) < 4 else f"{len(x['units'])} devices"
        bk = f"{x['booking']} {_md(x['booking_day'])}" if x["booking"] else ""
        out.append(f"| {x['id']} | {x['title']} | {dev} | {x['task']} | {_md(x['last'])} | {_md(x['due'])} | {_md(x['limit'])} | "
                   f"{bk} | {x['text']} |")
    out += ["", "Each finding's action:", ""]
    for k, t in PC.ACTIONS.items():
        if any(x["kind"] == k for x in f["findings"]):
            out.append(f"- **{f['kinds'][k]}.** {t}")
    out += ["", "## Agreements", "", "| Agreement | Cases | Agree |", "|---|---:|---:|"]
    for a in f["agreements"]:
        out.append(f"| {a['title']} | {a['checked']} | {a['checked'] - len(a['misses'])} |")
    outside = next((a.get("outside") for a in f["agreements"] if a["key"] == "assets"), None)
    if outside:
        out += ["", f"Outside the asset register's scope (`config/assets.yaml` facility_kinds): {', '.join(outside)}."]
    out += ["", "## Register", "", "| Device | Task | Last done | From | Due | Grace ends | Booked | Status |", "|---|---|---|---|---|---|---|---|"]
    for x in f["lines"]:
        src = "record" if x["records"] else (x["opening"]["source"].lower() if x["opening"] else "")
        st = S[x["status"]] + (f" ({x['finding']})" if x["finding"] else "")
        bk = ", ".join(f"{b['id']} {_md(b['day'])}" for b in x["bookings"])
        out.append(f"| {x['unit']} | {x['task']} | {_md(x['last'])} | {src} | {_md(x['due'])} | {_md(x['limit'])} | {bk} | {st} |")
    p = f["procedure"]
    out += ["", "## The coverage procedure (Landlord SLA section 11.1)", "", f"{p['principle']} {p['register']} {p['grace']}", ""]
    for s in p["steps"]:
        out.append(f"- **{s['id']} {s['name']}.** {s['text']}")
    out += ["", p["credits"], "", "## How it works", "",
            "- **Program.** `config/pm_program.yaml` expands each line of the Landlord SLA's maintenance schedule to the devices "
            "it covers (`docs/site/devices.json`), with its interval, grace, and basis. Monthly tasks are due in each calendar "
            "month; the rest by days (quarterly 91, semiannual 182, annual 365, three-year 1,095).",
            "- **Last completion.** The latest PM record for the line: the Hall A history for the Hall A CDU filters (the CDU "
            "telemetry and the predictions follow it), the July, August, and September Measurement Periods for everything else. "
            "Before the records begin, the opening register (`data/pm_coverage/opening.csv`, its own random stream) holds the "
            "last completion from the Landlord's maintenance system or the acceptance test at commissioning.",
            "- **Walk.** From the last completion, each due date must have a booking on or before its grace limit; a booking "
            "is taken as done on its day and the next due date follows from it, until the horizon.",
            "- **Load bank.** Required only when a monthly exercise did not reach 30% of nameplate (NFPA 110); every "
            "recorded exercise did, so it is not required.",
            "- **Synthetic layer.** The opening register is placed by its own planner rule (each line's next due date booked in "
            "time, or after the horizon), then one planted record problem of each kind; a line with no records and no date that "
            "satisfies the rule is listed as found. The checks never read the answer key. `python scripts/render_pm.py "
            "--robustness 60` scores 60 forward schedules and opening registers.", ""]
    return "\n".join(out)


def robustness(n: int) -> int:
    t0 = time.time()
    tot = {"planted": 0, "found": 0, "as_found": 0, "as_found_hit": 0, "false_positives": 0}
    by_kind: dict[str, list[int]] = {}
    for k in range(n):
        sched = ForwardSchedule(2000 + k).run()["schedule"]
        out = OpeningRegister(3000 + k, schedule=sched).run()
        opening = [{**o, "last_done": o["last_done"]} for o in out["opening"]]
        r = PC.analyse(schedule=sched, opening=opening)
        sc = PC.score(r, out["key"])
        for key in tot:
            tot[key] += sc[key]
        found = {ln: f["kind"] for f in r["findings"] for ln in f["lines"]}
        for p in out["key"]["planted"]:
            by_kind.setdefault(p["kind"], [0, 0])[0] += found.get(p["line"]) == p["kind"]
            by_kind[p["kind"]][1] += 1
        if sc["found"] != sc["planted"] or sc["as_found_hit"] != sc["as_found"] or sc["false_positives"]:
            print(f"  case {k}: {sc}")
    print(f"Robustness, {n} forward schedules and opening registers: planted {tot['found']}/{tot['planted']} found "
          f"({', '.join(f'{k} {a}/{b}' for k, (a, b) in sorted(by_kind.items()))}), as found {tot['as_found_hit']}/{tot['as_found']}, "
          f"{tot['false_positives']} false positives in {time.time() - t0:.0f} s")
    return 0 if tot["found"] == tot["planted"] and tot["as_found_hit"] == tot["as_found"] and not tot["false_positives"] else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--robustness", type=int, metavar="N")
    args = ap.parse_args()
    if args.robustness:
        return robustness(args.robustness)
    f = prepare()
    text = markdown(f)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/render_pm.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    sc = PC.score(PC.analyse(), json.loads((LAYER / "answer_key.json").read_text(encoding="utf-8")))
    c = f["count"]
    print(f"PM coverage: {f['devices']} devices, {len(f['lines'])} lines ({c['current']} current, {c['booked']} booked, "
          f"{c['booked_late']} booked late, {c['not_booked']} due with nothing booked, {c['overdue']} overdue, {c['no_baseline']} no baseline, "
          f"{c['not_required']} not required); {len(f['findings'])} findings ({sc['found']} of {sc['planted']} planted, "
          f"{sc['as_found_hit']} of {sc['as_found']} as found, {sc['false_positives']} false positives); "
          f"{len(f['agreements'])} agreements, {sum(a['checked'] - len(a['misses']) for a in f['agreements'])} of "
          f"{sum(a['checked'] for a in f['agreements'])}")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
