#!/usr/bin/env python3
"""Render the Emergency tab: the procedures, the decision tree, the call lists, and the Incident Commander runbook.

Usage:
    python scripts/render_emergency.py                 # write docs/emergency/*.md
    python scripts/render_emergency.py --check         # fail if docs/emergency/ is stale (CI)
    python scripts/render_emergency.py --html OUT.html # write the page (scripts/build_site.py does this)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import emergency, sitenav  # noqa: E402
from scorecard.emergency import tree_paths  # noqa: E402

OUT = ROOT / "docs" / "emergency"
FOOT = "*Synthetic data for a portfolio demonstration; all names, contacts, and events are fictional.*"


def _when(m: int) -> str:
    return "at once" if m == 0 else f"within {m} min"


def _hm(m: int | None) -> str:
    if m is None:
        return "—"
    h, r = divmod(m, 60)
    return (f"{h} h" + (f" {r:02d} min" if r else "")) if h else f"{m} min"


def markdown_command(c: dict) -> str:
    rb, sv = c["runbook"], c["runbook"]["severity"]
    L = ["<!-- GENERATED by scripts/render_emergency.py from config/incident_command.yaml, the agreements, and the data. Do not edit by hand. -->", "",
         "# Incident Commander runbook", "", rb["intro"], "",
         f"**Who commands.** {rb['commander']}", ""] + [f"- {r}" for r in rb["roles"]] + ["",
         f"**Bridge.** {rb['bridge_rule']}", "",
         "*The runbook is the Customer's. A missed step is a process finding for the post-incident review, not an SLA default, and carries no credit.*", "",
         "## Severity and command", "", "| Priority | IT Partner SLA | Landlord SLA | Acknowledge | On site | Restore | Updates | Command |", "|---|---|---|---|---|---|---|---|"]
    for p in sv["priorities"]:
        L.append(f"| {p['id']} | {p['names']['IT Partner']} | {p['names']['Landlord']} | {_hm(p['acknowledge_min'])} | {_hm(p['engaged_on_site_min'])} | "
                 f"{_hm(p['restore_min'])} | {'every ' + _hm(p['update_cadence_min']) if p['update_cadence_min'] else '—'} | {p['command']} |")
    L += ["", "Internal severity (the Customer's; not shared with the partners):", "", "| Level | Escalation |", "|---|---|"]
    L += [f"| {x['id']} {x['name']} | {x['escalation']} |" for x in sv["internal"]]
    L += ["", "## Paging tree for a critical alarm", ""]
    L += [f"- **{'+' + str(x['min']) + ' min' if x['min'] else 'At once'}:** {x['who']}. {x['via']}." for x in rb["paging"]["levels"]]
    L += ["", "## The steps", ""]
    n = 0
    for ph in rb["phases"]:
        L += [f"### {ph['name']}", ""]
        for s in [x for x in rb["steps"] if x["phase"] == ph["id"]]:
            n += 1
            L.append(f"{n}. {s['text']} *Clock: {s['due']}.*")
        L.append("")
    L += [f"**Restoration handoff ({rb['handoff']['id']}).** {rb['handoff']['rule']}", "", f"**Afterwards.** {rb['post_incident']}", "",
          "## Status-update templates", ""]
    for t in rb["templates"]:
        L += [f"**{t['name']}** ({t['when']})", "", f"> {t['body']}", ""] + [f"- {r}" for r in t["rules"]] + [""]
    for r in c["replays"]:
        sm = r["summary"]
        L += [f"## Replay: {r['title']}", "", f"{r['ref']} against the runbook ({r['review']}): {sm['met']} of {sm['steps']} steps met, {sm['missed']} missed.", "",
              "| Step | Check | From (UTC) | At (UTC) | Elapsed | Target | Result |", "|---|---|---|---|---|---|---|"]
        for i, s in enumerate(r["steps"], 1):
            for c_ in s["checks"]:
                tgt = "—" if c_["target"] is None else f"{c_['target']} business days" if c_["minutes"] is None and c_["elapsed"] else f"{c_['target']} min"
                fr = (c_["from"] or "—")[11:19] or c_["from"] or "—"
                at = (c_["at"] or "none")[11:19] or c_["at"] or "none"
                L.append(f"| {i} | {c_['label']}{' (' + c_['detail'] + ')' if c_['detail'] else ''} | {fr} | {at} | {c_['elapsed'] or '—'} | {tgt} | "
                         f"{'Met' if c_['met'] else '**Missed**'} |")
        L += ["", "Why each missed step was missed:", ""]
        L += [f"- **Step {i}:** {s['note']}" for i, s in enumerate(r["steps"], 1) if s["note"]]
        L += ["", "### Bridge comms log", "", "| UTC | Central | Party | Who | Said |", "|---|---|---|---|---|"]
        L += [f"| {e['t'][11:19]} | {e['local']} | {e['party']} | {e['role']}{' to ' + e['to'] if e.get('to') else ''} | {e['text']} |" for e in r["log"]]
    L += ["", "*Synthetic data for a portfolio demonstration; all names and events are fictional.*", ""]
    return "\n".join(L)


def markdown_procedures(e: dict) -> str:
    L = ["<!-- GENERATED by scripts/render_emergency.py from config/emergency.yaml, the agreements, the runbook, and the site model. Do not edit by hand. -->", "",
         "# Emergency procedures and call lists", "", e["intro"], "", "## Always first", ""] + [f"- {x}" for x in e["always_first"]]
    s = e["site"]
    L += ["", f"**Site.** {s['name']}, {s['address']}. {s['responders']} {s['assembly']}", "", "## Which procedure: the decision tree", ""]
    nodes = e["tree"]["nodes"]
    names = {t["id"]: t["name"] for t in e["types"]}
    for nid, n in nodes.items():
        L += [f"**{n['q']}**", ""]
        L += [f"- {o['label']}: " + (f"**{names[o['to'][5:]]}**" if o["to"].startswith("type:") else f"next, *{nodes[o['to']]['q']}*") for o in n["options"]]
        L.append("")
    L += [f"Every path ({len(tree_paths(e['tree']))}) ends at a procedure.", ""]
    for t in e["types"]:
        L += [f"## {t['name']}", "", f"**Priority.** {t['priority']}", "", f"**Bridge leads.** {', '.join(t['leads'])}.", ""]
        for ph in t["phases"]:
            acts = [a for a in t["actions"] if a["phase"] == ph["id"]]
            L += [f"### {ph['name']}", ""] + [f"{i}. **{a['owner']}.** {a['text']}" for i, a in enumerate(acts, 1)] + [""]
        L += ["### Questions for the bridge", ""] + [f"- {q}" for q in t["questions"]]
        L += ["", "### Before anything returns to service", ""] + [f"- [ ] {x}" for x in t["rts"]]
        L += ["", "### Who is told", "", "| Who | When | Why |", "|---|---|---|"]
        L += [f"| {n['name']} ({n['contact']}) | {_when(n['within_min'])} | {n['why']} |" for n in t["notify"]]
        L += ["", "### Partner documents (referenced, not written here)", ""] + [f"- {x}" for x in t["partner_docs"]]
        ev = [x for x in e["events"] if x["id"] in t["samples"]]
        L += ["", "**In the sample month:** " + ("; ".join(f"{', '.join(x['records'])} ({x['start'][:10]})" for x in ev) if ev else "no P1 record of this type.") + "", ""]
    b = e["bridge"]
    L += ["## The bridge", "", f"**{b['name']}.** Dial-in {b['dial_in']}, passcode {b['passcode']}. Backup: {b['backup']}. Video: {b['video']}. {b['chat']}.", ""]
    L += [f"- {r}" for r in b["rules"]] + ["", "| Role | Who | Does |", "|---|---|---|"] + [f"| {r['role']} | {r['who']} | {r['does']} |" for r in b["roles"]]
    L += ["", f"Roll call: {', '.join(b['roll_call'])}.", "", "## Call lists", "",
          f"Each contact is checked by a test call or message at least every {e['verify_within_days']} days; as of {e['as_of']}, anything older is flagged.", "",
          "| Group | Role | Phone | Email | Last verified |", "|---|---|---|---|---|"]
    for c in e["contacts"]:
        phone = "; ".join(f"{x['label']} {x['start']} to {x['end']}: {x['who']} {x['phone']}" for x in c["rota_shifts"]) if c.get("rota") else c.get("phone", "")
        L.append(f"| {c['group']} | {c['role']} | {phone} | {c.get('email', '')} | {c['verified']}{' **(overdue: ' + str(c['age_days']) + ' days)**' if c['stale'] else ''} |")
    L += ["", "## Leadership notification tiers", "", "| Tier | " + " | ".join(t["short"] for t in e["types"]) + " |", "|---|" + "---|" * len(e["types"])]
    for tr in e["tiers"]:
        L.append(f"| {tr['name']} | " + " | ".join(next((_when(n['within_min']) for n in t["notify"] if n["tier"] == tr["id"]), "") for t in e["types"]) + " |")
    L += ["", "## Sources", ""] + [f"- {x}" for x in e["sources"]] + ["", FOOT, ""]
    return "\n".join(L)


def outputs() -> dict[Path, str]:
    e = emergency.build()
    return {OUT / "EMERGENCY_PROCEDURES.md": markdown_procedures(e), OUT / "incident-command.md": markdown_command(e["command"])}


def html_page() -> str:
    tpl = sitenav.inject((ROOT / "templates" / "emergency.html").read_text(encoding="utf-8"), "emergency")
    return sitenav.finish(tpl.replace("__DATA__", json.dumps(emergency.build(), sort_keys=True).replace("</", "<\\/")))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--html", metavar="OUT")
    args = ap.parse_args()
    if args.html:
        Path(args.html).parent.mkdir(parents=True, exist_ok=True)
        Path(args.html).write_text(html_page(), encoding="utf-8")
        print(f"Wrote {args.html}")
        return 0
    docs = outputs()
    if args.check:
        stale = [p for p, t in docs.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date. Run: python scripts/render_emergency.py")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, t in docs.items():
        p.write_text(t, encoding="utf-8", newline="\n")
        print(f"Wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
