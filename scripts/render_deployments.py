#!/usr/bin/env python3
"""Render the deployment program: docs/deployments/DEPLOYMENT_PLAN.md, docs/deployments/HALL_C_READINESS.md, and the Deployments tab (/deployments/).

The Hall B GB300 NVL72 rollout as gates and steps (config/deployments.yaml), the calculation sheet from the
site model, the authority and statewide determinations, and each rack's reported and measured milestones
(src/scorecard/deployments.py). Hall C readiness: the 800 VDC pilot's commissioning (L1 to L5), the Customer's readiness
gates, the first-compute forecast, pilot spares, and record checks (src/scorecard/readiness.py).

Usage:
    python scripts/render_deployments.py            # write both documents
    python scripts/render_deployments.py --check    # fail if either is stale (CI)
    python scripts/render_deployments.py --robustness 60   # plant and find the record checks in 60 generated months
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from datetime import date, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import deployments as D  # noqa: E402
from scorecard import readiness as RD  # noqa: E402
from scorecard import sitenav  # noqa: E402

OUT = ROOT / "docs" / "deployments" / "DEPLOYMENT_PLAN.md"
OUT_READY = ROOT / "docs" / "deployments" / "HALL_C_READINESS.md"
KIND = {"internal": "Internal", "third_party": "Third party", "ahj": "Authority"}


def num(x: float, unit: str) -> str:
    return f"{x:,.1f} {unit}" if unit in ("kPa", "K", "LPM") else f"{x:,.0f} {unit}"


def stamp(iso: str | None) -> str:
    return iso[:16].replace("T", " ") + " UTC" if iso else "-"


def markdown(b: dict) -> str:
    p, roles = b["program"], b["roles"]
    role = lambda r: f"{roles[r]['name']}"
    L = [f"# {p['name']}", "",
         "*Generated by `scripts/render_deployments.py` from `config/deployments.yaml`, `site/site.yaml`, the IT Partner SLA, "
         "and the sample data. Do not edit by hand.*", "",
         f"> {' '.join(b['meta']['disclaimer'].split())} Checked {b['meta']['checked']}.", "",
         f"{p['hall_name']}: {p['racks_total']} {p['rack_model']} racks in {p['waves_total']} waves (one per row), "
         f"rack cycle target {p['cycle_days']} days. Program {p['id']}.", "",
         "## Contents", "", "1. [Gates](#gates)", "2. [Authority and permits](#authority-and-permits)",
         "3. [Statewide determinations](#statewide-determinations)", "4. [Calculation sheet](#calculation-sheet)",
         "5. [Cabling and connections](#cabling-and-connections)", "6. [Rack status](#rack-status)",
         "7. [Steps](#steps)", "8. [Record](#record)", "9. [Record checks](#record-checks)", "10. [Sign-off roles](#sign-off-roles)",
         "11. [Sources](#sources)", "",
         "## Gates", "", "| Gate | Name | Owner | Steps | Exit criteria |", "|---|---|---|---|---|"]
    for g in b["gates"]:
        n = sum(1 for s in b["steps"] if s["gate"] == g["id"])
        L.append(f"| {g['id']} | {g['name']} | {role(g['owner'])} | {n}{' per rack' if g['per_rack'] else ''} | {g['exit']} |")
    a = b["authority"]
    L += ["", "## Authority and permits", "", f"**Profile in use: {a['name']}** (`{a['id']}`; the other profile: "
          + ", ".join(f"{v} (`{k}`)" for k, v in b["profiles"].items() if k != a["id"]) + ").", "", a["summary"], "",
          "| Permit | Issued by | When | Inspections |", "|---|---|---|---|"]
    for pm in a["permits"]:
        L.append(f"| {pm['id']} {pm['name']} | {role(pm['by'])} | {pm['when']} | {'; '.join(pm['inspections']) or '-'} |")
    L += ["", "## Statewide determinations", "", "| Item | Requirement | What the site model says |", "|---|---|---|"]
    for d in b["statewide"]:
        L.append(f"| {d['id']} {d['name']} | {d['detail']} | {d['result']} |")
    L += ["", "## Calculation sheet", "",
          "Every check reads the site model. Checks at the reported peak that fail are not design errors: they name the control "
          "that keeps the design figure true.", "",
          "| Group | Check | Load | Capacity | Utilization | Limit | Result | Basis |", "|---|---|---|---|---|---|---|---|"]
    for r in b["calc"]:
        if r["passed"] is None:
            L.append(f"| {r['group']} | {r['check']} | {num(r['load'], r['unit'])} | - | - | - | Figure | {r['basis']} |")
        else:
            res = "Pass" if r["passed"] else f"**Control:** {r['control']}" if r["control"] else "**Fail**"
            L.append(f"| {r['group']} | {r['check']} | {num(r['load'], r['unit'])} | {num(r['capacity'], r['unit'])} | "
                     f"{r['utilization']:.0%} | {r['limit']:.0%} | {res} | {r['basis']} |")
    L += ["", "Calculation inputs the site model does not hold:", ""]
    for k, v in b["calc_inputs"].items():
        L.append(f"- `{k}` = {v['value']}: {v['basis']}")
    c = b["cabling"]
    L += ["", "## Cabling and connections", "", "Counted from the device directory (the site model).", "",
          "| Item | Count |", "|---|---|",
          f"| Racks | {c['racks']} |", f"| Compute trays | {c['compute_trays']} |", f"| InfiniBand rails per tray | {c['rails']} |",
          f"| Leaf switches | {c['leaf_switches']} |", f"| Back-end links (tray to leaf) | {c['backend_links']:,} ({c['links_per_rack']} per rack) |",
          f"| Power cords (A and B, one per tap-off) | {c['power_cords']} |", f"| Coolant hoses (supply and return) | {c['coolant_hoses']} |"]
    rk = b["racks"]
    L += ["", "## Rack status", "",
          f"As of {stamp(rk['as_of'])}, the end of the sample window. Reported: the IT Partner's milestone report. Measured: the "
          "Customer's 24-hour burn-in record and the scheduler's Validated Handoff (the CSL-09 measurement).", "",
          "| State | Racks |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in sorted(rk["counts"].items())]
    L += ["", "| Rack | Wave | Power group | Planned receipt | Committed handoff | Last reported | Measured burn-in | Measured handoff | State |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in rk["racks"]:
        L.append(f"| {r['rack']} | {r['wave']} | {r['group']} | {stamp(r['planned_receipt'])} | {stamp(r['committed_handoff'])} | "
                 f"{r['last_reported'] or '-'} | {stamp(r['measured_burn_in'])} | {stamp(r['measured_handoff'])} | {r['state']} |")
    L += ["", "## Steps", ""]
    for g in b["gates"]:
        L += [f"### {g['id']} {g['name']}", ""]
        for s in [s for s in b["steps"] if s["gate"] == g["id"]]:
            head = f"#### {s['id']} {s['name']}"
            L += [head, "", f"- **Document:** {s['doc']['id']} ({s['doc']['kind']})", f"- **Performed by:** {role(s['owner'])}"]
            if s.get("milestone"):
                L.append(f"- **Rack milestone:** {s['milestone']}, target day {s['target_days']} from receipt (IT Partner SLA)")
            if s.get("level"):
                L.append(f"- **Commissioning level:** {s['level']}")
            if s["after"]:
                L.append(f"- **After:** {', '.join(s['after'])}")
            if s.get("when"):
                L.append(f"- **When:** {s['when']}")
            if s["standards"]:
                L.append(f"- **Standards:** {'; '.join(b['standards'][x]['name'] for x in s['standards'])}")
            L += ["", "Procedure:", ""] + [f"{i}. {x}" for i, x in enumerate(s["procedure"], 1)]
            L += ["", "Acceptance:", ""] + [f"- {x}" for x in s["acceptance"]]
            L += ["", f"Records: {'; '.join(s['records'])}.", "",
                  f"Sign-off, in order: {' -> '.join(role(r) for r in s['signoff'])}."]
            if s["inspections"]:
                L += ["", "Inspections:", ""] + [f"- {KIND[i['kind']]}: {role(i['by'])}, {i['what']}" for i in s["inspections"]]
            L.append("")
    rec, gs = b["record"], {g["gate"]: g for g in b["gate_status"]}
    L += ["## Record", "",
          "The partners' Jira projects (read through `src/scorecard/jira_import.py` with `config/jira_fields.yaml`), the Customer's "
          "step records, sign-offs, inspections, and permits (`data/deployments/`), joined into one deployment work order per unit "
          "of work. A work order is complete when it is done, every sign-off role has signed, and every required inspection passed.", "",
          "| Gate | Work orders complete | State |", "|---|---|---|"]
    L += [f"| {g['id']} {g['name']} | {gs[g['id']]['complete']} of {gs[g['id']]['total']} | {'closed' if gs[g['id']]['closed'] else 'open'} |"
          for g in b["gates"]]
    L += ["", "| Jira project | Partner | Issues | Done | In progress | Open |", "|---|---|---|---|---|---|"]
    L += [f"| {k} {v['name']} | {v['partner']} | {v['issues']} | {v['by_state']['done']} | {v['by_state']['in progress']} | {v['by_state']['open']} |"
          for k, v in rec["projects"].items()]
    L += ["", "Program work orders (rack work orders are listed on the tab):", "",
          "| Work order | Step | Source | Done | Signed | Complete |", "|---|---|---|---|---|---|"]
    L += [f"| {w['id']} | {w['step']} | {w['source']} | {stamp(w['done'])} | {w['signed']} of {len(w['signoffs'])} | {'yes' if w['complete'] else 'no'} |"
          for w in rec["work_orders"] if not w["rack"]]
    L += ["", "Permit register (fictional numbers):", "", "| Permit | Number | Issued | Finaled | Status |", "|---|---|---|---|---|"]
    L += [f"| {p['permit']} {p['name']} | {p['number'] or '-'} | {stamp(p.get('issued'))} | {stamp(p.get('finaled'))} | {p['status']}"
          f"{': ' + p['reason'] if p.get('reason') else ''} |" for p in rec["permits"]]
    L += ["", "Inspection records:", "", "| Record | Step | By | When | Result | Note |", "|---|---|---|---|---|---|"]
    L += [f"| {i['id']} | {i['step']} | {role(i['by'])} | {stamp(i['at'])} | {i['result']} | {i['note'] or '-'} |" for i in rec["inspections"]]
    L += ["", "Determinations recorded:", ""]
    L += [f"- {d['id']} ({stamp(d['recorded'])}, {d['step']}): {d['result']}" for d in rec["determinations"]]
    L += ["", "## Record checks", "",
          f"Records that do not reconcile, found from the work orders alone. A missing signature counts once the step has been Done "
          f"for {b['signoff_window_days']} days. A finding means the records disagree, not that the work was not done; the work order "
          "names the records to compare.", ""]
    L += [f"- **{v}.** {b['check_help'][k]}" for k, v in b["check_names"].items()]
    L += ["", "| Check | Work order | Partner | Finding |", "|---|---|---|---|"]
    L += [f"| {f['check']} | {f['wo']} | {f['partner']} | {f['text']} |" for f in b["findings"]] or ["| - | - | - | No findings |"]
    if c := b["self_check"]:
        dc = c["decoys"]
        n = lambda x, one, many: f"{x} {one if x == 1 else many}"  # noqa: E731
        L += ["", f"Self-check: found **{c['detected']} of {c['planted']}** planted records, **{len(c['false_positives'])} false positives**. "
              f"Decoys not flagged: {n(dc.get('signatures_pending_in_window', 0), 'work order with signatures still inside the window', 'work orders with signatures still inside the window')}, "
              f"{n(dc.get('inspections_failed_then_passed', 0), 'inspection that failed and then passed on a retest', 'inspections that failed and then passed on a retest')}, "
              f"{n(dc.get('handoff_minutes_after_leak_test', 0), 'tap-off energized minutes after its leak test', 'tap-offs energized minutes after their leak tests')}. "
              "The checks cannot read the answer key."]
    L += ["", "## Sign-off roles", "", "| Role | Organization | Duty |", "|---|---|---|"]
    L += [f"| {v['name']} | {v['org']} | {v['duty']} |" for v in roles.values()]
    L += ["", "## Sources", ""]
    L += [f"- {k}: {v}" for k, v in b["sources"].items()]
    return "\n".join(L) + "\n"


def readiness_markdown(r: dict, roles: dict) -> str:
    p, fc = r["program"], r["forecast"]
    role = lambda x: roles[x]["name"]
    sc = {s["id"]: s for s in r["scripts"]}
    late = fc["slip_days"]
    L = [f"# {r['meta']['title']}", "",
         "_Generated by `scripts/render_deployments.py` from `config/readiness.yaml`, `site/site.yaml`, and the record in "
         "`data/readiness/`. Do not edit by hand._", "", f"> {' '.join(r['meta']['disclaimer'].split())}", "",
         f"{p['hall_name']}: {p['racks']} racks ({p['rack_model']}). Record as of {stamp(p['as_of'])}.", "",
         "## First compute", "",
         f"- Committed: {fc['committed']}",
         f"- Forecast: {fc['first_compute']} ({'on time' if late <= 0 else f"{late} day{'s' if late > 1 else ''} late"})",
         f"- Critical path: {' > '.join(fc['critical_path'])}", "",
         "## Commissioning", "", "| System | Model | " + " | ".join(r["levels"]) + " |", "|---|---|" + "---|" * len(r["levels"])]
    for s in r["systems"] + [{"id": "HALL-C", "name": "Hall C, integrated", "model": "Hall-wide"}]:
        cells = []
        for lv in r["levels"]:
            k = r["matrix"].get(s["id"], {}).get(lv)
            if not k:
                cells.append("")
            elif sc[k]["passed_at"]:
                cells.append(f"passed {sc[k]['passed_at'][:10]}")
            else:
                cells.append(f"{sc[k]['state']}, forecast {sc[k]['forecast']}")
        L.append(f"| {s['id']} {s['name']} | {s['model']} | " + " | ".join(cells) + " |")
    L += ["", "| Level | Name | Performed by | Signs, in order |", "|---|---|---|---|"]
    L += [f"| {k} | {v['name']} | {role(v['by'])} | {', '.join(role(x) for x in v['sign'])} |" for k, v in r["levels"].items()]
    oc = r["open_by_category"]
    L += ["", f"Issues log: {len(r['issues'])} issues, open now: Category 1 {oc[1]}, Category 2 {oc[2]}, Category 3 {oc[3]}.", ""]
    L += [f"- Category {k}: {v}" for k, v in r["issue_categories"].items()]
    L += ["", "## Readiness gates", ""]
    for g in r["gates"]:
        L += [f"### {g['id']} {g['name']} ({g['done']} of {g['total']} done)", "", "| Item | Owner | State | Done | Forecast |", "|---|---|---|---|---|"]
        L += [f"| {it['id']} {it['name']} | {role(it['owner'])} | {it['state']} | {it['done'][:10] or '-'} | {it['forecast']} |" for it in g["items"]]
        L.append("")
    L += ["## Pilot spares", "", "| FRU | Minimum | Received to date |", "|---|---|---|"]
    L += [f"| {s['fru']} | {s['minimum']} | {s['received']} |" for s in r["spares"]]
    L += ["", "## Record checks", ""]
    L += [f"- **{f['check']}** ({f['ref']}): {f['text']}" for f in r["findings"]] or ["- No findings."]
    if c := r["self_check"]:
        L += ["", f"Self-check: found {c['detected']} of {c['planted']} planted records, {len(c['false_positives'])} false positives. "
              "The checks cannot read the answer key."]
    return "\n".join(L) + "\n"


def prepare() -> dict:
    b = D.build()
    b["readiness"] = RD.build()
    b["program"]["racks_total"] = len(b["racks"]["racks"])
    b["program"]["waves_total"] = len({r["wave"] for r in b["racks"]["racks"]})
    return b


def html_page() -> str:
    tpl = sitenav.inject((ROOT / "templates" / "deployments.html").read_text(encoding="utf-8"), "deployments")
    return sitenav.finish(tpl.replace("__DATA__", json.dumps(prepare(), sort_keys=True).replace("</", "<\\/")))


def robustness(n: int) -> int:
    from scorecard.sla_model import load_sla
    from scorecard.synthetic import SiteGenerator, write_dataset
    from scorecard.synthetic import deployments as G
    syn = yaml.safe_load((ROOT / "config" / "synthetic.yaml").read_text(encoding="utf-8"))
    tot: dict[str, list[int]] = {}
    fps, decoys = [], {}
    from scorecard.synthetic import readiness as GR
    rtot: dict[str, list[int]] = {}
    rfps, rdecoys = [], {}
    for k in range(n):
        with tempfile.TemporaryDirectory() as tmp:
            d = Path(tmp)
            write_dataset(SiteGenerator(load_sla(), syn, start=date(2025, 1, 6) + timedelta(weeks=4 * k), seed=2000 + k).run(), d)
            G.write_deployments(G.DeploymentRecordLayer(d, 2000 + k).run(), d / "deployments", "robustness")
            b = D.build(d, rec_dir=d / "deployments")
            w = json.loads((d / "manifest.json").read_text(encoding="utf-8"))["window"]
            GR.write_readiness(GR.ReadinessRecordLayer(w["end"], 2000 + k).run(), d / "readiness", "robustness")
            rc = RD.build(d / "readiness")["self_check"]
        for kind, (a, t) in rc["by_kind"].items():
            x = rtot.setdefault(kind, [0, 0])
            x[0], x[1] = x[0] + a, x[1] + t
        for kind, v in rc["decoys"].items():
            rdecoys[kind] = rdecoys.get(kind, 0) + v
        rfps += [(k, x) for x in rc["false_positives"]]
        for m in rc["missed"]:
            print(f"  month {k}: readiness missed {m}")
        c = b["self_check"]
        for kind, (a, t) in c["by_kind"].items():
            x = tot.setdefault(kind, [0, 0])
            x[0], x[1] = x[0] + a, x[1] + t
        for kind, v in c["decoys"].items():
            decoys[kind] = decoys.get(kind, 0) + v
        fps += [(k, x) for x in c["false_positives"]]
        for m in c["missed"]:
            print(f"  month {k}: missed {m}")
    print(f"Deployment record checks on {n} generated programs (planted records moved each month):")
    for kind, (a, t) in sorted(tot.items()):
        print(f"  {kind:<14} found {a}/{t}")
    print(f"  decoys         {decoys.get('signatures_pending_in_window', 0)} signatures inside the window, "
          f"{decoys.get('inspections_failed_then_passed', 0)} failed-then-passed inspections, "
          f"{decoys.get('handoff_minutes_after_leak_test', 0)} tap-offs energized minutes after the leak test; {len(fps)} false positives")
    for k, x in fps:
        print(f"  month {k}: false positive: {x}")
    print(f"Hall C readiness record checks on {n} generated programs:")
    for kind, (a, t) in sorted(rtot.items()):
        print(f"  {kind:<18} found {a}/{t}")
    print(f"  decoys             {rdecoys.get('retested_then_passed', 0)} levels failed then passed on a retest, "
          f"{rdecoys.get('cat2_open_at_pass', 0)} levels passed with a Category 2 open, "
          f"{rdecoys.get('signed_same_day_after_run', 0)} signed the same day after the run; {len(rfps)} false positives")
    for k, x in rfps:
        print(f"  month {k}: readiness false positive: {x}")
    ok = tot and all(a == t for a, t in tot.values()) and not fps
    ok = ok and rtot and all(a == t for a, t in rtot.values()) and not rfps
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--html", metavar="OUT", help="also write the page")
    ap.add_argument("--robustness", type=int, metavar="N")
    args = ap.parse_args()
    if args.robustness:
        return robustness(args.robustness)
    b = prepare()
    docs = {OUT: markdown(b), OUT_READY: readiness_markdown(b["readiness"], b["roles"])}
    if args.check:
        stale = [p for p, text in docs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date. Run: python scripts/render_deployments.py")
        return 1 if stale else 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    for p, text in docs.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    if args.html:
        out = Path(args.html)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(html_page(), encoding="utf-8", newline="\n")
    controls = sum(1 for r in b["calc"] if r["control"])
    wos = b["record"]["work_orders"]
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(b['steps'])} steps in {len(b['gates'])} gates, "
          f"{sum(1 for r in b['calc'] if r['passed'] is not None)} checks ({controls} need the power-limit control), "
          f"racks {b['racks']['counts']}, {sum(w['complete'] for w in wos)} of {len(wos)} work orders complete, "
          f"{len(b['findings'])} record findings")
    if c := b["self_check"]:
        print(f"Detected {c['detected']} of {c['planted']} planted, {len(c['false_positives'])} false positives")
    r = b["readiness"]
    print(f"Wrote {OUT_READY.relative_to(ROOT)}: first compute committed {r['forecast']['committed']}, forecast "
          f"{r['forecast']['first_compute']}; {len(r['findings'])} record findings")
    if c := r["self_check"]:
        print(f"Hall C readiness: detected {c['detected']} of {c['planted']} planted, {len(c['false_positives'])} false positives")
    return 0


if __name__ == "__main__":
    sys.exit(main())
