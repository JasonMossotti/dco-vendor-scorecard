#!/usr/bin/env python3
"""Daily operations standup: one page per day (reports/standup.md), reconciled with the weekly packs.

Usage:
    python scripts/render_standup.py                          # write reports/standup.md
    python scripts/render_standup.py --check                  # fail if the report is stale
    python scripts/render_standup.py --robustness 60 --jobs 4 # generate 60 months and reconcile their days with their weeks

The Operations page's opening view (/ops/) is built from prepare() by scripts/render_ops.py.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
import time
from datetime import date, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import standup as SU  # noqa: E402
from scorecard.change_calendar import hm_local, parse  # noqa: E402

OUT = ROOT / "reports" / "standup.md"
PERMITS = {"loto": "Lockout", "eewp": "Energized work", "height": "Working at height", "hot": "Hot work", "confined": "Confined space"}


def prepare() -> dict:
    """Everything the report and the page show (scorecard.standup.page_data)."""
    return SU.page_data()


def _t(iso: str) -> str:
    return hm_local(parse(iso))


def _staff(x: dict) -> str:
    it, ll = x["it"], x["landlord"]
    s = f"IT Partner {it['badged']} of {it['rostered']} technicians badged in (shift lead {it['lead']}), Landlord {ll['badged']} of {ll['rostered']} engineers"
    if "security" in x:
        s += f", Security Partner {x['security']['badged']} of {x['security']['rostered']} posts"
    return s


def markdown(f: dict) -> str:
    w = f["window"]
    tm = f["times"]
    out = ["# Daily operations standup", "",
           f"Site AUS-1 (synthetic), {w['start'][:10]} to {(parse(w['end']) - timedelta(days=1)).date()}. Generated by "
           "`scripts/render_standup.py` from the records and the layers beside them; do not edit by hand. Times are Central.", "",
           f"One page per day for the contract's daily standup (`sla/common.yaml`, governance), as the records stood at "
           f"{tm['standup']}. The operations day runs from the night shift handover at {tm['handover_night']} to the next one, the "
           "boundary the weekly packs use, so a week's seven days add up to its pack.", "",
           "**Top three today** follows `config/standup.yaml`: an open P1 or P2 incident at risk of missing its restore clock "
           f"(half its restore time used), then a redundancy group reduced at the standup, then a deployment step past its due date on "
           f"a rack due for handoff within {f['rule']['handoff_lookahead_days']} days or already late (one per rack). Nothing here is a "
           "finding; the standup shows what the other views found.", "",
           "## Weeks against their packs", "",
           "| Week | Days | P1 and P2 incidents opened (IT Partner) | (Landlord) | Findings raised | Permits issued | Changes worked | Technician hours badge-verified |",
           "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for wk, x in f["weeks"].items():
        d, p = x["days"], x["pack"]
        pct = 100 * d["present"] / d["committed"] if d["committed"] else 0
        out.append(f"| {wk} | {d['days']} | {d['it_p12']} (pack {p['it_p12']}) | {d['landlord_p12']} (pack {p['landlord_p12']}) | "
                   f"{d['findings']} (pack {p['findings']}) | {d['permits']} (pack {p['permits']}) | {d['changes']} | "
                   f"{d['present']:,.0f} of {d['committed']:,.0f} ({pct:.1f}%, CSL-10) |")
    out += ["", f"Every week reconciles: {'yes' if not f['reconcile'] else 'no: ' + '; '.join(f['reconcile'])}. "
                f"Changes worked over the month: {sum(x['days']['changes'] for x in f['weeks'].values())}, the Calendar's "
                f"{f.get('calendar_jobs', 0)} data-week jobs that were not deferred.", ""]
    for d in f["days"]:
        out += [f"## {d['weekday']} {d['date']} ({d['week']}, day {d['week_day']})", ""]
        if d["top3"]:
            out += [f"{n}. {t['text']}" for n, t in enumerate(d["top3"], 1)]
        else:
            out.append("Top three: nothing meets the rule.")
        o = d["overnight"]
        out += ["", f"- **Overnight:** {len(o['records'])} records opened"
                + (f" ({', '.join(r['ref'] + ' ' + r['priority'] for r in o['records'])})" if o["records"] else "")
                + (f"; redundancy reduced: {'; '.join(r['text'] for r in o['redundancy'])}" if o["redundancy"] else "")
                + (f"; reported: {', '.join(x['ref'] for x in o['safety'])}" if o["safety"] else "") + "."]
        if d["incidents"]:
            out.append("- **Open P1 and P2:** " + "; ".join(
                f"{', '.join(i['refs']) or i['unit']} {i['priority']} ({i['partner']}), {SU._hm(i['used_min'])} of {SU._hm(i['target_min'])}"
                + (" at risk" if i["at_risk"] else "") for i in d["incidents"]) + ".")
        if d["work"]:
            out.append("- **Work today:** " + "; ".join(
                f"{j['id']} {_t(j['start'])} to {_t(j['end'])}" + (f" ({', '.join(j['conflicts'])})" if j["conflicts"] else "")
                for j in d["work"]) + ".")
        due = [s for s in d["steps"] if not s["overdue"]]
        late = [s for s in d["steps"] if s["overdue"]]
        if d["steps"]:
            out.append(f"- **Deployment steps:** {len(due)} due today, {len(late)} overdue"
                       + (f" ({sum(s['critical'] for s in late)} on a rack due for handoff)" if late else "") + ".")
        if d["hallc"]:
            out.append(f"- **Hall C scripts scheduled:** {', '.join(x['id'] for x in d['hallc'])}.")
        if d["permits"]:
            out.append("- **Permits:** " + "; ".join(f"{p['permit']} {PERMITS.get(p['type'], p['type'])} {p['point']}"
                                                     + (" (open at the standup)" if p["open_at_standup"] else "") for p in d["permits"]) + ".")
        if d["spares"]:
            out.append("- **Spares below minimum:** " + "; ".join(f"{s['fru']} ({s['where']}) {s['balance']} of {s['minimum']}" for s in d["spares"]) + ".")
        out.append(f"- **Staffing:** night shift {_staff(d['staffing'][0])}; day shift by the standup {_staff(d['staffing'][1])}.")
        oc = d["on_call"]
        out.append(f"- **On call:** {oc['now']['primary']} (primary), {oc['now']['secondary']} (secondary); tonight {oc['tonight']['primary']} and "
                   f"{oc['tonight']['secondary']}. Duty managers: {', '.join(oc['duty_managers'].values())}.")
        c = d["close"]
        out.append(f"- **Day close ({tm['handover_night']}):** P1 and P2 opened IT Partner {c['incidents']['it']}, Landlord "
                   f"{c['incidents']['landlord']}; findings raised {c['findings']['total']}; changes worked {c['changes']['worked']}"
                   + (f" (overran: {', '.join(c['changes']['overrun'])})" if c["changes"]["overrun"] else "")
                   + f"; permits issued {c['permits']}; deployment steps done {c['steps_done']}; technician hours "
                   f"{c['technician_hours']['present']:,.0f} of {c['technician_hours']['committed']:,.0f}.")
        out.append("")
    return "\n".join(out)


def robustness_month(k: int) -> dict:
    """A generated month (no layers beside it): its days against its weekly packs, and the top-three rule."""
    from scorecard.sla_model import load_sla
    from scorecard.synthetic import SiteGenerator, write_dataset
    from scorecard.synthetic.security import generate
    from scorecard.weekly import WeeklyData, build_all
    syn = yaml.safe_load((ROOT / "config" / "synthetic.yaml").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp) / "sample"
        write_dataset(SiteGenerator(load_sla(), syn, start=date(2025, 1, 6) + timedelta(weeks=4 * k), seed=2000 + k).run(), d)
        generate(d, d / "security")
        wd = WeeklyData(d)
        s = SU.Standup(d, weekly=wd, layers=False)
        days = [s.day(x) for x in s.days]
        misses = SU.reconcile(days, build_all(wd))
    rule = []
    for x in days:
        r = [t["rule"] for t in x["top3"]]
        risk = [i for i in x["incidents"] if i["at_risk"]]
        if r != sorted(r) or len(r) > 3 or (risk and (not r or r[0] != 1)):
            rule.append(f"{x['date']}: {r}")
    return {"month": k, "days": len(days), "weeks": len({x["week"] for x in days}), "misses": misses, "rule": rule,
            "incidents": sum(x["close"]["incidents"]["it"] + x["close"]["incidents"]["landlord"] for x in days),
            "findings": sum(x["close"]["findings"]["total"] for x in days), "top": sum(len(x["top3"]) for x in days)}


def robustness(n: int, jobs: int = 1) -> int:
    from concurrent.futures import ProcessPoolExecutor
    t0 = time.time()
    if jobs > 1:
        with ProcessPoolExecutor(jobs) as ex:
            res = list(ex.map(robustness_month, range(n)))
    else:
        res = [robustness_month(k) for k in range(n)]
    for r in res:
        for m in r["misses"] + r["rule"]:
            print(f"  month {r['month']}: {m}")
    weeks = sum(r["weeks"] for r in res)
    ok_weeks = weeks - sum(len({m.split()[0] for m in r["misses"]}) for r in res)
    print(f"Daily standup on {n} generated months ({time.time() - t0:.0f} s): {sum(r['days'] for r in res):,} days, "
          f"{ok_weeks}/{weeks} weeks reconcile with their packs (incidents opened {sum(r['incidents'] for r in res):,}, "
          f"findings raised {sum(r['findings'] for r in res):,}, technician hours); top three follows the rule on "
          f"{sum(r['days'] for r in res) - sum(len(r['rule']) for r in res):,} of {sum(r['days'] for r in res):,} days "
          f"({sum(r['top'] for r in res):,} items)")
    return 0 if ok_weeks == weeks and not any(r["rule"] for r in res) else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--robustness", type=int, metavar="N")
    ap.add_argument("--jobs", type=int, default=1)
    args = ap.parse_args()
    if args.robustness:
        return robustness(args.robustness, args.jobs)
    f = prepare()
    text = markdown(f)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/render_standup.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    top = sum(len(d["top3"]) for d in f["days"])
    print(f"Daily standup: {len(f['days'])} days, {len(f['weeks'])} weeks, "
          f"{'every week reconciles with its pack' if not f['reconcile'] else 'NOT reconciled: ' + '; '.join(f['reconcile'])}; "
          f"{top} top-three items")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0 if not f["reconcile"] else 1


if __name__ == "__main__":
    sys.exit(main())
