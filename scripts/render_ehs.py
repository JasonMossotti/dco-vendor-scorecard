#!/usr/bin/env python3
"""EHS (safety): the monthly EHS report by partner, the record checks, and the report (reports/ehs.md).

Usage:
    python scripts/render_ehs.py                          # write reports/ehs.md
    python scripts/render_ehs.py --check                  # fail if the report is stale
    python scripts/render_ehs.py --robustness 60 --jobs 4 # generate 60 months with their EHS layers and score them

The Operations page's Safety view (/ops/#ehs) is built from prepare() by scripts/render_ops.py.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
from datetime import date, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import ehs as E  # noqa: E402
from scorecard.change_calendar import hm_local, parse  # noqa: E402

LAYER = ROOT / "data" / "ehs"
OUT = ROOT / "reports" / "ehs.md"


def prepare() -> dict:
    """Everything the report and the page show (scorecard.ehs.page_data)."""
    return E.page_data()


def _t(iso: str) -> str:
    return f"{iso[:10]} {hm_local(parse(iso))}" if iso else ""


def markdown(f: dict) -> str:
    w, rep = f["window"], f["report"]
    P = f["partners"]
    out = ["# EHS (safety)", "",
           f"Site AUS-1 (synthetic), {w['start'][:10]} to {(parse(w['end']) - timedelta(days=1)).date()}. Generated by "
           "`scripts/render_ehs.py` from the records and `data/ehs/`; do not edit by hand. Times are Central.", "",
           "The contract's monthly EHS report by partner (`sla/common.yaml`, ehs), and four checks of the work permits and "
           "training records against the job records, the badge records, and what the devices recorded. Reported injuries, "
           "near misses, first aid cases, and stop-work uses are never findings and never count against anyone.", "",
           "## Monthly EHS report", "",
           "| Partner | Hours worked | Recordables | TRIR | DART rate | Near misses | Stop-work uses | First aid | Permits issued | Open corrective actions |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for k, r in rep.items():
        out.append(f"| {P[k]} | {r['hours']:,.1f} | {r['recordables']} | {r['trir']:.2f} | {r['dart_rate']:.2f} | {r['near_miss']} | "
                   f"{r['stop_work']} | {r['first_aid']} | {r['permits']} | {r['open_actions']} |")
    out += ["", "Hours worked come from the badge records: the IT Partner's main door in to out, each Landlord shift the engineer "
                "badged in for, each Security Partner post shift the guard badged in at the post for. TRIR and DART are per "
                "200,000 hours.", "", "## Findings", "",
            "A finding means the permit, training, badge, and device records do not reconcile. It opens an investigation by "
            "Customer EHS, which decides any violation class; it is not a judgment of anyone.", "",
            "| ID | Kind | Records | When | Owner | What |", "|---|---|---|---|---|---|"]
    for x in f["findings"]:
        out.append(f"| {x['id']} | {x['title']} | {', '.join(x['refs'])} | {_t(x['at'])} | {x['owner']} | {x['text']} |")
    out += ["", "Each finding's action:", ""]
    for k, t in E.ACTIONS.items():
        if any(x["kind"] == k for x in f["findings"]):
            out.append(f"- **{E.KINDS[k]}.** {t}")
    out += ["", "## Agreements", "", "| Agreement | Cases | Agree | Explained by a finding |", "|---|---:|---:|---:|"]
    for a in f["agreements"]:
        out.append(f"| {a['title']} | {a['checked']} | {a['checked'] - len(a['misses'])} | {a['explained']} |")
    out += ["", "## Permits", "", "| Permit | Type | Job | Work | Point | Issued | Closed | Named |", "|---|---|---|---|---|---|---|---|"]
    for p in f["permits"]:
        named = ", ".join(p["workers"]) + (f"; second person {p['attendant']}" if p["attendant"] else "")
        out.append(f"| {p['permit']} | {f['permit_types'][p['type']]['name']} | {p['job']} | {p['title']} | {p['point']} | "
                   f"{_t(p['issued'])} | {_t(p['closed'])} | {named} |")
    out += ["", "## Training records", "", "| Course | Renewal | People holding it | Current at month end | Expiring in the next 60 days |",
            "|---|---:|---:|---:|---:|"]
    for c in f["courses"]:
        out.append(f"| {c['name']} | {c['months']} months | {c['holders']} | {c['current']} | {len(c['expiring'])} |")
    out += ["", "## Reported events", "", "| Event | Kind | Partner | When | Where | What | Corrective action |", "|---|---|---|---|---|---|---|"]
    names = {"near_miss": "Near miss", "stop_work": "Stop-work use", "first_aid": "First aid", "recordable": "Recordable"}
    for x in f["events"]:
        state = f"closed {x['action_closed'][:10]}" if x["action_closed"] else f"open, due {x['action_due'][:10]}"
        out.append(f"| {x['event']} | {names[x['kind']]} | {P[x['partner']]} | {_t(x['at'])} | {x['where']} | {x['what']} | {x['action']} ({state}) |")
    out += ["", "## Post-incident reviews", ""]
    out += [f"- **{p['pir']}** ({p['injuries']} injuries): {p['screening']} {p['referral']}" for p in f["pir"]]
    out += ["", "## How it works", "",
            "- **Which jobs need a permit.** From the records (`config/ehs.yaml`): a Landlord MOP or maintenance record by its work "
            "type (a tap-off retorque, a UPS maintenance, a CDU filter change, and a chiller maintenance need a lockout; a new "
            "tap-off onto live busway needs an energized work permit approved in advance by the Customer and a working-at-height "
            "permit), a corrective work order on power or a UPS by its fault class, and the IT Partner's overhead cabling step "
            "(milestone M5) by its milestone.",
            "- **The work.** What the device recorded where one records it (the tap-off breaker, the UPS bypass, the CDU pump, the "
            "chiller lockout), else the job record.",
            "- **Checks.** A job with no permit of a type it needs, or a tap-off breaker opened with no permit open on it; a "
            "lockout recorded outside the device's isolation; a person named on a permit (or an electrical task's engineer) "
            "without a current completion of every course the work needs; a permit closed before the work ended.",
            "- **Not findings.** Injuries, near misses, first aid cases, and stop-work uses are reported, counted, and never "
            "findings (29 CFR 1904.35).",
            "- **Synthetic layer.** `data/ehs/` is generated on its own random stream with four planted record problems; the checks "
            "never read the answer key. `python scripts/render_ehs.py --robustness 60 --jobs 4` scores 60 generated months.", ""]
    return "\n".join(out)


def robustness_month(k: int) -> dict:
    from scorecard.sla_model import load_sla
    from scorecard.synthetic import SiteGenerator, write_dataset
    from scorecard.synthetic.ehs import EhsLayer, write_ehs
    from scorecard.synthetic.security import generate
    syn = yaml.safe_load((ROOT / "config" / "synthetic.yaml").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp)
        write_dataset(SiteGenerator(load_sla(), syn, start=date(2025, 1, 6) + timedelta(weeks=4 * k), seed=2000 + k).run(), d)
        generate(d, d / "security")
        layer = EhsLayer(d, 2000 + k, security_dir=d / "security")
        out = layer.run()
        write_ehs(layer, out, d / "ehs")
        r = E.analyse(E.load_month(d), E.load(d / "ehs"), security_dir=d / "security")
        sc = E.score(r["findings"], out["key"])
        fps = [f"{f['kind']} {f['refs']}: {f['text'][:140]}" for f in r["findings"]
               if not any(f["kind"] == x["kind"] and x["ref"] in f["refs"] for x in out["key"])]
    ag = {c.name: [c.checked - len(c.misses) + r["explained"].get(c.name, 0), c.checked, c.misses[:3]] for c in r["agreements"]}
    return {"month": k, "agreements": ag, "score": sc, "fps": fps, "permits": len(out["permits"]),
            "kinds": {x["kind"]: sum(1 for f in r["findings"] if f["kind"] == x["kind"] and x["ref"] in f["refs"])
                      for x in out["key"] if x["source"] == "planted"}}


def robustness(n: int, jobs: int = 1) -> int:
    from concurrent.futures import ProcessPoolExecutor
    t0 = time.time()
    if jobs > 1:
        with ProcessPoolExecutor(jobs) as ex:
            res = list(ex.map(robustness_month, range(n)))
    else:
        res = [robustness_month(k) for k in range(n)]
    tot: dict[str, list[int]] = {}
    sc = {"planted": 0, "found": 0, "as_found": 0, "as_found_expected": 0, "false_positives": 0}
    by_kind: dict[str, list[int]] = {}
    for r in res:
        for name, (a, b, misses) in r["agreements"].items():
            x = tot.setdefault(name, [0, 0])
            x[0], x[1] = x[0] + a, x[1] + b
            if a != b:
                for mi in misses:
                    print(f"  month {r['month']}: {name}: {mi}")
        for key in sc:
            sc[key] += r["score"][key]
        for kind, hit in r["kinds"].items():
            v = by_kind.setdefault(kind, [0, 0])
            v[0], v[1] = v[0] + bool(hit), v[1] + 1
        for fp in r["fps"]:
            print(f"  month {r['month']}: false positive {fp}")
        if r["score"]["found"] < r["score"]["planted"]:
            print(f"  month {r['month']}: {r['score']}")
    print(f"EHS agreements on {n} generated months ({time.time() - t0:.0f} s; {sum(r['permits'] for r in res):,} permits):")
    for name, (a, b) in tot.items():
        print(f"  {name:<10} {a:,}/{b:,} (agree, or explained by a finding)")
    print(f"EHS findings on {n} generated months: {sc['found']} of {sc['planted']} planted found "
          f"({', '.join(f'{k} {a}/{b}' for k, (a, b) in sorted(by_kind.items()))}), {sc['as_found']} of {sc['as_found_expected']} "
          f"as found (the dataset's own ground truth), {sc['false_positives']} false positives")
    ok = all(a == b for a, b in tot.values()) and sc["found"] == sc["planted"] and sc["as_found"] == sc["as_found_expected"] \
        and sc["false_positives"] == 0
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--robustness", type=int, metavar="N")
    ap.add_argument("--jobs", type=int, default=1)
    args = ap.parse_args()
    if args.robustness:
        return robustness(args.robustness, args.jobs)
    f = prepare()
    text = markdown(f)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/render_ehs.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    key = json.loads((LAYER / "answer_key.json").read_text(encoding="utf-8"))
    sc = E.score(f["findings"], key)
    ok = sum(a["checked"] - len(a["misses"]) + a["explained"] for a in f["agreements"])
    print(f"EHS: {f['summary']['jobs']} jobs, {f['summary']['permits']} permits, {f['summary']['findings']} findings "
          f"({sc['found']} of {sc['planted']} planted, {sc['as_found']} of {sc['as_found_expected']} as found, {sc['false_positives']} false positives); "
          f"{len(f['agreements'])} agreements, {ok} of {sum(a['checked'] for a in f['agreements'])} cases agree or are explained")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
