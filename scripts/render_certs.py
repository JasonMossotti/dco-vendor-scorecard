#!/usr/bin/env python3
"""Certification register and work gate: the report (reports/certifications.md) and the robustness run.

Usage:
    python scripts/render_certs.py                          # write reports/certifications.md
    python scripts/render_certs.py --check                  # fail if the report is stale
    python scripts/render_certs.py --robustness 60 --jobs 4 # generate 60 months with their layers and score them

The Training page's Certifications view (/training/) is built from prepare() by scripts/render_training.py.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
from datetime import date, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import certifications as C  # noqa: E402
from scorecard.change_calendar import hm_local, parse  # noqa: E402

LAYER = ROOT / "data" / "certs"
OUT = ROOT / "reports" / "certifications.md"
STATUS = {"met_expected": "Met", "below_expected": "Below Expected", "below_minimum": "Minimum default",
          "deep_below_minimum": "Minimum default (deep)", "no_events": "n/a"}


def prepare() -> dict:
    """Everything the report and the page show (scorecard.certifications.page_data)."""
    return C.page_data()


def _t(iso: str) -> str:
    return f"{iso[:10]} {hm_local(parse(iso))}" if iso else ""


def _pct(v) -> str:
    return "n/a" if v is None else f"{v:.2f}%"


def markdown(f: dict) -> str:
    w, P, s = f["window"], f["partners"], f["summary"]
    out = ["# Certification register and work gate", "",
           f"Site AUS-1 (synthetic), {w['start'][:10]} to {(parse(w['end']) - timedelta(days=1)).date()}, register read as of "
           f"{f['as_of'][:10]}. Generated by `scripts/render_certs.py` from the records, `data/certs/`, and `data/ehs/training.csv`; "
           "do not edit by hand. Times are Central. People are IDs only.", "",
           "Every credential each partner's people must hold (`config/certifications.yaml`), checked against every shift the badge "
           "records verify and every record that names who did the work. A finding means the credential records and the work "
           "records do not reconcile; it opens a Customer review and changes no credit.", "",
           "## Summary", "",
           f"- **{s['people']} people** (IT Partner, Landlord, and Security Partner), {s['credentials']} credential records and "
           f"{s['ehs_courses']} EHS course completions.",
           f"- **{s['work']:,} pieces of work checked:** {s['shifts']} badge-verified shifts and {s['records']} records.",
           f"- **{s['findings']} findings:** " + ", ".join(f"{n} {f['kinds'][k].lower()}" for k, n in s["by_kind"].items() if n) + ".",
           f"- **KM-15 Training and Certification Currency:** "
           + (f"{f['km15']['actual']:.1f}% against 100% ({f['km15']['detail']})." if f["km15"] else "not measured."),
           f"- **{s['notices']} renewal notices** to draft in the next {f['notice_rules']['horizon_days']} days.", "",
           "## Findings", "",
           "| ID | Kind | Partner | Person | Credential | From | Records | Shifts |", "|---|---|---|---|---|---|---|---:|"]
    for x in f["findings"]:
        out.append(f"| {x['id']} | {x['title']} | {x['owner']} | {x['person'] or '-'} | {x['credential_name'] or '-'} | {_t(x['at'])} | "
                   f"{', '.join(x['records']) or '-'} | {x['shifts']} |")
    out += [""]
    out += [f"- **{x['id']}.** {x['text']}" for x in f["findings"]]
    out += ["", "Each finding's action:", ""]
    for k, t in C.ACTIONS.items():
        if any(x["kind"] == k for x in f["findings"]):
            out.append(f"- **{f['kinds'][k]}.** {t}")
    out += ["", "## Agreements", "", "| Agreement | Cases | Agree | Explained by a finding |", "|---|---:|---:|---:|"]
    for a in f["agreements"]:
        out.append(f"| {a['title']} | {a['checked']} | {a['checked'] - len(a['misses'])} | {a['explained']} |")
    out += ["", "## Staffing with the qualification rule", "",
            "The staffing service levels count only hours worked by people with current qualifications (IT SLA staffing, "
            "Landlord SLA staffing, Security SLA posts). Recalculated with the register beside the published value; the "
            "published scorecards do not change.", "",
            "| Service level | Partner | Expected / Minimum | Published | Status | With the rule | Status | Not counted | People |",
            "|---|---|---|---:|---|---:|---|---:|---|"]
    for r in f["staffing"]:
        out.append(f"| {r['csl']} {r['name']} | {r['partner']} | {r['expected']}% / {r['minimum']}% | {_pct(r['published'])} | "
                   f"{STATUS[r['published_status']]} | {_pct(r['adjusted'])} | {STATUS[r['adjusted_status']]} | {r['lost']} {r['unit']} | "
                   f"{', '.join(r['people']) or '-'} |")
    out += ["", "## Monthly credential reports", "",
            "| Partner | As of | People | Required credentials | Reported current | Reported lapsed | Register lapsed |",
            "|---|---|---:|---:|---:|---|---|"]
    for r in f["reported"]:
        real = f["measured_lapsed"].get(r["partner"], [])
        out.append(f"| {P[r['partner']]} | {r['as_of'][:10]} | {r['people']} | {r['required']} | {r['current_pct']}% | "
                   f"{', '.join(x.replace(':', ' ') for x in r['lapsed'].split(';') if x) or 'none'} | "
                   f"{', '.join(x.replace(':', ' ') for x in real) or 'none'} |")
    out += ["", "## Credentials", "", "| Credential | Partner | Renewal | Holders | Current at month end | Basis |",
            "|---|---|---:|---:|---:|---|"]
    for c in f["catalog"]:
        who = P.get(c["partner"], "EHS course")
        out.append(f"| {c['name']} | {who} | {str(c['months']) + ' months' if c['months'] else 'does not expire'} | {c['holders']} | "
                   f"{c['current']} | {c['basis']} |")
    out += ["", "## Renewal notices", "",
            f"Credentials that lapse in the {f['notice_rules']['horizon_days']} days after {f['as_of'][:10]}. Notices go to each "
            f"partner's training coordinator at {', '.join(str(d) for d in f['notice_rules']['lead_days'])} days before expiry, "
            "copied to the Customer site lead. Drafted on the page, never sent.", "",
            "| Expires | Partner | Person | Credential | Days left | Notices |", "|---|---|---|---|---:|---|"]
    for n in f["notices"]:
        steps = "; ".join(f"{x['lead']} d {x['date']}" + (" (due now)" if x["lead"] == n["stage"] else "") for x in n["notices"])
        out.append(f"| {n['expires'][:10]} | {P[n['partner']]} | {n['person']} | {n['name']} | {n['days']} | {steps} |")
    out += ["", "## Forward schedule: qualified people available", "",
            f"Each job on the forward schedule against how many of its owner's people hold every credential the work type needs on "
            f"the day (at least {f['notice_rules']['bench_min']}).", "",
            "| Job | Starts | Owner | Needs | Qualified people |", "|---|---|---|---|---:|"]
    for b in f["bench"]:
        out.append(f"| {b['id']} {b['title']} | {_t(b['start'])} | {b['owner']} | {'; '.join(b['names'])} | "
                   f"{b['holders']}{' (short)' if b['short'] else ''} |")
    out += ["", "## How it works", "",
            "- **Who must hold what.** Each role's credentials (`config/certifications.yaml` roles) plus the EHS courses the role "
            "holds (`config/ehs.yaml`). Work adds its own: an IT Partner incident by category (ESD for tray, optic, and power work, "
            "liquid cooling for tray and leak work, fiber for optics, the rack model's FRU authorization for tray and switch "
            "trays), a Landlord work order by fault class and a maintenance record by system (UPS, CDU, chiller, generator, "
            "VESDA training; EPA 608 for chiller maintenance), a destruction certificate's operator, and every guard post shift "
            "(the Texas DPS Level III commission and SA requalification; STG for the posts that draw a shotgun).",
            "- **When.** A shift at its start, when the badge records verify it by the same rule as the staffing service level; an "
            "incident when the technician was on site; a work order when engaged; a maintenance record when completed.",
            "- **Reports.** Each partner's monthly credential report is compared with what the register shows lapsed at the "
            "month end.",
            "- **KM-15.** The IT Partner's badge-verified shifts on which the person held every role credential; the IT "
            "scorecard reads it from here.",
            "- **Synthetic layer.** `data/certs/` is generated on its own random stream with four planted record problems (five "
            "answer-key entries); the checks never read the answer key. `python scripts/render_certs.py --robustness 60 --jobs 4` "
            "scores 60 generated months.", ""]
    return "\n".join(out)


def robustness_month(k: int) -> dict:
    from scorecard.sla_model import load_sla
    from scorecard.synthetic import SiteGenerator, write_dataset
    from scorecard.synthetic.certs import CertsLayer, write_certs
    from scorecard.synthetic.ehs import EhsLayer, write_ehs
    from scorecard.synthetic.security import generate
    syn = yaml.safe_load((ROOT / "config" / "synthetic.yaml").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp)
        write_dataset(SiteGenerator(load_sla(), syn, start=date(2025, 1, 6) + timedelta(weeks=4 * k), seed=2000 + k).run(), d)
        generate(d, d / "security")
        el = EhsLayer(d, 2000 + k, security_dir=d / "security")
        write_ehs(el, el.run(), d / "ehs")
        layer = CertsLayer(d, 2000 + k, d / "security", d / "ehs")
        out = layer.run()
        write_certs(layer, out, d / "certs")
        site, reg = C.load_site(d, d / "security"), C.load(d / "certs", d / "ehs")
        r = C.analyse(site, reg, ehs_layer=d / "ehs")
        sc = C.score(r["findings"], out["key"])
        fps = [f"{f['kind']} {f['refs'][:3]} {f['credential']}: {f['text'][:160]}" for f in r["findings"]
               if not any(f["kind"] == x["kind"] and x["ref"] in f["refs"] and (not x.get("credential") or x["credential"] == f["credential"])
                          for x in out["key"])]
        staff = C.staffing(site, reg)
    ag = {c.name: [c.checked - len(c.misses) + r["explained"].get(c.name, 0), c.checked, c.misses[:3]] for c in r["agreements"]}
    return {"month": k, "agreements": ag, "score": sc, "fps": fps, "work": len(r["work"]),
            "kinds": {f"{x['kind']}:{x.get('credential') or ''}": any(f["kind"] == x["kind"] and x["ref"] in f["refs"] for f in r["findings"])
                      for x in out["key"]},
            "staff": [(s["csl"], s["published"], s["adjusted"]) for s in staff]}


def robustness(n: int, jobs: int = 1) -> int:
    from concurrent.futures import ProcessPoolExecutor
    t0 = time.time()
    if jobs > 1:
        with ProcessPoolExecutor(jobs) as ex:
            res = list(ex.map(robustness_month, range(n)))
    else:
        res = [robustness_month(k) for k in range(n)]
    tot: dict[str, list[int]] = {}
    sc = {"planted": 0, "found": 0, "as_found": 0, "as_found_expected": 0, "false_positives": 0}
    by_kind: dict[str, list[int]] = {}
    for r in res:
        for name, (a, b, misses) in r["agreements"].items():
            x = tot.setdefault(name, [0, 0])
            x[0], x[1] = x[0] + a, x[1] + b
            if a != b:
                for mi in misses:
                    print(f"  month {r['month']}: {name}: {mi}")
        for key in sc:
            sc[key] += r["score"][key]
        for kind, hit in r["kinds"].items():
            v = by_kind.setdefault(kind, [0, 0])
            v[0], v[1] = v[0] + bool(hit), v[1] + 1
        for fp in r["fps"]:
            print(f"  month {r['month']}: false positive {fp}")
        if r["score"]["found"] < r["score"]["planted"] or r["score"]["as_found"] < r["score"]["as_found_expected"]:
            print(f"  month {r['month']}: {r['score']}")
    print(f"Certification agreements on {n} generated months ({time.time() - t0:.0f} s; {sum(r['work'] for r in res):,} pieces of work):")
    for name, (a, b) in tot.items():
        print(f"  {name:<8} {a:,}/{b:,} (agree, or explained by a finding)")
    print(f"Certification findings on {n} generated months: {sc['found']} of {sc['planted']} planted found "
          f"({', '.join(f'{k} {a}/{b}' for k, (a, b) in sorted(by_kind.items()))}), {sc['as_found']} of {sc['as_found_expected']} "
          f"as found (the EHS layer's lapse), {sc['false_positives']} false positives")
    ok = all(a == b for a, b in tot.values()) and sc["found"] == sc["planted"] and sc["as_found"] == sc["as_found_expected"] \
        and sc["false_positives"] == 0
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--robustness", type=int, metavar="N")
    ap.add_argument("--jobs", type=int, default=1)
    args = ap.parse_args()
    if args.robustness:
        return robustness(args.robustness, args.jobs)
    f = prepare()
    text = markdown(f)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/render_certs.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    key = json.loads((LAYER / "answer_key.json").read_text(encoding="utf-8"))
    sc = C.score(f["findings"], key)
    ok = sum(a["checked"] - len(a["misses"]) + a["explained"] for a in f["agreements"])
    print(f"Certifications: {f['summary']['people']} people, {f['summary']['work']} pieces of work, {f['summary']['findings']} findings "
          f"({sc['found']} of {sc['planted']} planted, {sc['as_found']} of {sc['as_found_expected']} as found, {sc['false_positives']} false positives); "
          f"{len(f['agreements'])} agreements, {ok} of {sum(a['checked'] for a in f['agreements'])} cases agree or are explained; "
          f"KM-15 {f['km15']['actual'] if f['km15'] else 'n/a'}%")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
