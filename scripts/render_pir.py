#!/usr/bin/env python3
"""Render post-incident reviews: the Markdown review in docs/pir/ and the interactive page for GitHub Pages.

Usage:
    python scripts/render_pir.py                 # write docs/pir/*.md
    python scripts/render_pir.py --check         # fail if docs/pir/ is stale (CI)
    python scripts/render_pir.py --html OUT.html # write the interactive page (scripts/build_site.py does this)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import sitenav  # noqa: E402
from scorecard import command  # noqa: E402
from scorecard.pir import OSR, Dataset, build_index, build_review  # noqa: E402

SAMPLE = ROOT / "data" / "sample"
REVIEWS = ROOT / "pir" / "reviews"
BADGE_NOTE = ("Landlord badge readers record entries only, so two entries in a row mean the person left and came back; "
              "IT Partner readers record entries and exits.")
OUT = ROOT / "docs" / "pir"


def reviews() -> list[dict]:
    return [yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted(REVIEWS.glob("*.yaml"))]


def markdown(f: dict, a: dict) -> str:
    pl, sev, ehs, ls = a["plain_language"], a["severity"], a["ehs"], a["lessons"]
    im = f["impact"]
    L = [f"<!-- GENERATED by scripts/render_pir.py from pir/reviews/{a['id']}.yaml and the dataset. Do not edit by hand. -->", "",
         f"# {a['id']}: {a['title']}", "",
         f"**Status:** {a['status']} · **Blameless review:** findings describe systems and procedures, not individuals. "
         f"Interactive version: [Post-Incident Review page](https://jasonmossotti.github.io/dco-vendor-scorecard/pir/).", "",
         "| Incident date | Ticket | Work order | MOP | Unit | Uptime severity (OSR) | Internal severity | Priority | Incident Commander | Review meeting |",
         "|---|---|---|---|---|---|---|---|---|---|",
         f"| {f['date']} | {f['ticket'] or '—'} | {f['work_order'] or '—'} | {', '.join(f['mops']) or '—'} | {f['unit']} | {sev['osr_level']} {OSR[sev['osr_level']][0]} | "
         f"{sev['internal']} | {sev['priority']} | {a['incident_commander']} | {a['review_meeting']} |", "",
         f"*OSR {sev['osr_level']} ({OSR[sev['osr_level']][0]}): {OSR[sev['osr_level']][1]} {sev['osr_rationale']}*", "",
         "## In plain language", ""]
    for q, k in (("What happened?", "what_happened"), ("Who was affected?", "who_was_affected"), ("Why did it happen?", "why"),
                 ("What are we doing about it?", "what_we_are_doing")):
        L += [f"**{q}** {pl[k]}", ""]
    lb = f["labels"]
    L += [f"| {lb['duration']} | {lb['offline']} | GPU-hours lost | {lb['split']} | Injuries |",
          "|:-:|:-:|:-:|:-:|:-:|", f"| {im['duration']} | {im['gpus']} | {im['gpu_hours_total']} | {im['gpu_hours_landlord']} / {im['gpu_hours_it']} | {im['injuries']} |", "",
          "## Summary (technical)", "", a["summary_technical"], "",
          f"- **Trigger:** {a['trigger']}", f"- **Detection:** {a['detection']}", f"- **Resolution:** {a['resolution']}", "",
          "## Response against targets", "", "| Measure | From (UTC) | To (UTC) | Elapsed | Target | Result |", "|---|---|---|---|---|---|"]
    for m in f["metrics"]:
        L.append(f"| {m['measure']}{' (' + m['note'] + ')' if m['note'] else ''} | {m['from'][11:19]} | {m['to'][11:19]} | {m['elapsed']} | {str(m['target']) + ' min' if m['target'] else '—'} | "
                 f"{'—' if m['met'] is None else 'Met' if m['met'] else '**Missed**'} |")
    L += ["", "## Alarm and event timeline (exact source records)", "", BADGE_NOTE, "", "| UTC | Central | Party | Event | Source | Record |", "|---|---|---|---|---|---|"]
    for r in f["timeline"]:
        L.append(f"| {r['t'][11:19]} | {r['local']} | {r['party']} | {r['event'].replace('|', '/')} | `{r['source']}` | "
                 f"{('`' + r['record'].replace('|', '/') + '`') if r['record'] else ''} |")
    at = f["attribution"]
    rules = f" (rules {', '.join(at['rules'])})" if at["rules"] else ""
    evidence = f" {at['evidence'].rstrip('.')}." if at["evidence"] else ""
    fa3 = f" Under FA-3 the IT Partner's clock started at the Landlord's handoff, {f['handoff'][11:19]}Z." if f["handoff"] else ""
    L += ["", "## Attribution (Interface Agreement)", "", f"**Owner: {at['owner']}**{rules}.{evidence}{fa3}", "",
          "## Contract and compliance consequences", ""]
    L += [f"- Finding {x['id']} ({x['severity']}): {x['summary']}" for x in f["findings"]]
    c = f["csl"].get("OT-CSL-01")
    if c:
        L.append(f"- OT-CSL-01 Rack Power Availability measured {c['actual']:.4f}% against a Minimum of {c['minimum']}%: "
                 f"{c['status'].replace('_', ' ')}" + (f", credit ${c['credit']:,.0f}." if c["credit"] else "."))
    if f["mop_overrun"]:
        o = f["mop_overrun"]
        L.append(f"- {o['mop']} window ended {o['window_end'][11:19]}Z; its equipment was closed at {o['closed'][11:19]}Z, {o['overrun']} past the approved window.")
    L += ["", "## EHS screening", "", f"- **Injuries:** {ehs['injuries']}", f"- **Screening:** {ehs['screening']}", f"- **Referral:** {ehs['referral']}", "",
          "## Contributing factors", "", "| ID | Type | Factor |", "|---|---|---|"]
    L += [f"| {x['id']} | {x['type']} | {x['text']} |" for x in a["factors"]]
    for t, k in (("What went well", "went_well"), ("What went poorly", "went_poorly"), ("Where we got lucky", "lucky")):
        L += ["", f"## {t}", ""] + [f"- {x}" for x in ls[k]]
    L += ["", "## Action items", "", f"Status as of {a['status_as_of']}.", "", "| ID | Action | Factor | Owner | Priority | Due | Success criterion | Status |", "|---|---|---|---|---|---|---|---|"]
    L += [f"| {x['id']} | {x['action']} | {x['factor']} | {x['owner']} | {x['priority']} | {x['due']} | {x['success']} | {x['status']} |" for x in a["actions"]]
    L += ["", "## Communications log", "", "| Time | To | Message |", "|---|---|---|"]
    L += [f"| {x['local']} | {x['to']} | {x['message']} |" for x in a["communications"]]
    if f["repeats"]:
        L += ["", "## Repeat-event check", "", "Other records in the window on the same rack or busway; each is ruled in or out as related.", ""]
        for r in f["repeats"]:
            rl = a["repeat_rulings"][r["ref"]]
            L.append(f"- {r['ref']} ({r['opened'][:16].replace('T', ' ')}Z): {r['what']}. "
                     f"**{'Related' if rl['related'] else 'Not related'}:** {rl['reason']}")
    L += ["", "## Sign-off", "", "| Role | Signed |", "|---|---|"] + [f"| {s['role']} | {s['date']} |" for s in a["signoff"]]
    L += ["", "*Synthetic data for a portfolio demonstration; all names and events are fictional.*", ""]
    return "\n".join(L)


def _hm(m: int | None) -> str:
    if m is None:
        return "—"
    h, r = divmod(m, 60)
    return (f"{h} h" + (f" {r:02d} min" if r else "")) if h else f"{m} min"


def markdown_command(c: dict) -> str:
    rb, sv = c["runbook"], c["runbook"]["severity"]
    L = ["<!-- GENERATED by scripts/render_pir.py from config/incident_command.yaml, the agreements, and the data. Do not edit by hand. -->", "",
         "# Incident Commander runbook", "", rb["intro"], "",
         f"**Who commands.** {rb['commander']}", ""] + [f"- {r}" for r in rb["roles"]] + ["",
         f"**Bridge.** {rb['bridge_rule']}", "",
         "*The runbook is the Customer's. A missed step is a process finding for the post-incident review, not an SLA default, and carries no credit.*", "",
         "## Severity and command", "", "| Priority | IT Partner SLA | Landlord SLA | Acknowledge | On site | Restore | Updates | Command |", "|---|---|---|---|---|---|---|---|"]
    for p in sv["priorities"]:
        L.append(f"| {p['id']} | {p['names']['IT Partner']} | {p['names']['Landlord']} | {_hm(p['acknowledge_min'])} | {_hm(p['engaged_on_site_min'])} | "
                 f"{_hm(p['restore_min'])} | {'every ' + _hm(p['update_cadence_min']) if p['update_cadence_min'] else '—'} | {p['command']} |")
    L += ["", "Internal severity (the Customer's; not shared with the partners):", "", "| Level | Escalation |", "|---|---|"]
    L += [f"| {x['id']} {x['name']} | {x['escalation']} |" for x in sv["internal"]]
    L += ["", "## Paging tree for a critical alarm", ""]
    L += [f"- **{'+' + str(x['min']) + ' min' if x['min'] else 'At once'}:** {x['who']}. {x['via']}." for x in rb["paging"]["levels"]]
    L += ["", "## The steps", ""]
    n = 0
    for ph in rb["phases"]:
        L += [f"### {ph['name']}", ""]
        for s in [x for x in rb["steps"] if x["phase"] == ph["id"]]:
            n += 1
            L.append(f"{n}. {s['text']} *Clock: {s['due']}.*")
        L.append("")
    L += [f"**Restoration handoff ({rb['handoff']['id']}).** {rb['handoff']['rule']}", "", f"**Afterwards.** {rb['post_incident']}", "",
          "## Status-update templates", ""]
    for t in rb["templates"]:
        L += [f"**{t['name']}** ({t['when']})", "", f"> {t['body']}", ""] + [f"- {r}" for r in t["rules"]] + [""]
    for r in c["replays"]:
        sm = r["summary"]
        L += [f"## Replay: {r['title']}", "", f"{r['ref']} against the runbook ({r['review']}): {sm['met']} of {sm['steps']} steps met, {sm['missed']} missed.", "",
              "| Step | Check | From (UTC) | At (UTC) | Elapsed | Target | Result |", "|---|---|---|---|---|---|---|"]
        for i, s in enumerate(r["steps"], 1):
            for c_ in s["checks"]:
                tgt = "—" if c_["target"] is None else f"{c_['target']} business days" if c_["minutes"] is None and c_["elapsed"] else f"{c_['target']} min"
                fr = (c_["from"] or "—")[11:19] or c_["from"] or "—"
                at = (c_["at"] or "none")[11:19] or c_["at"] or "none"
                L.append(f"| {i} | {c_['label']}{' (' + c_['detail'] + ')' if c_['detail'] else ''} | {fr} | {at} | {c_['elapsed'] or '—'} | {tgt} | "
                         f"{'Met' if c_['met'] else '**Missed**'} |")
        L += ["", "Why each missed step was missed:", ""]
        L += [f"- **Step {i}:** {s['note']}" for i, s in enumerate(r["steps"], 1) if s["note"]]
        L += ["", "### Bridge comms log", "", "| UTC | Central | Party | Who | Said |", "|---|---|---|---|---|"]
        L += [f"| {e['t'][11:19]} | {e['local']} | {e['party']} | {e['role']}{' to ' + e['to'] if e.get('to') else ''} | {e['text']} |" for e in r["log"]]
    L += ["", "*Synthetic data for a portfolio demonstration; all names and events are fictional.*", ""]
    return "\n".join(L)


def outputs() -> dict[Path, str]:
    ds = Dataset(SAMPLE)
    out = {}
    for a in reviews():
        f = build_review(ds, a["ref"])
        out[OUT / f"{a['id']}.md"] = markdown(f, a)
    out[OUT / "incident-command.md"] = markdown_command(command.build())
    return out


def html_page() -> str:
    ds = Dataset(SAMPLE)
    rv = reviews()
    index = build_index(ds)
    # The devices one connection away are for search only, not text the page shows, so the popups skip them.
    near = {ref: f.pop("near") for ref, f in index.items()}
    data = {"index": index, "reviews": rv, "osr": {k: list(v) for k, v in OSR.items()}, "badge_note": BADGE_NOTE, "command": command.build()}
    tpl = sitenav.inject((ROOT / "templates" / "pir.html").read_text(encoding="utf-8"), "pir")
    tpl = tpl.replace("__NEAR__", json.dumps(near, sort_keys=True, separators=(",", ":")).replace("</", "<\\/"))
    return sitenav.finish(tpl.replace("__DATA__", json.dumps(data, sort_keys=True).replace("</", "<\\/")))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--html", metavar="OUT")
    args = ap.parse_args()
    if args.html:
        Path(args.html).parent.mkdir(parents=True, exist_ok=True)
        Path(args.html).write_text(html_page(), encoding="utf-8")
        print(f"Wrote {args.html}")
        return 0
    docs = outputs()
    if args.check:
        stale = [p for p, t in docs.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date. Run: python scripts/render_pir.py")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, t in docs.items():
        p.write_text(t, encoding="utf-8", newline="\n")
        print(f"Wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
