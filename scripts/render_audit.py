#!/usr/bin/env python3
"""The monthly quality audit: the sample, each record's checks, findings, agreements, and the report (reports/quality_audit.md).

Usage:
    python scripts/render_audit.py                  # write reports/quality_audit.md
    python scripts/render_audit.py --check          # fail if the report is stale
    python scripts/render_audit.py --sample 906856  # print the sample a seed draws from the month (anyone can reproduce it)
    python scripts/render_audit.py --robustness 60  # generate 60 months and score them (planted found, false positives)

The Scorecards page's Quality audit view (/app/#audit) is built from prepare() by scorecard.scorecards_page.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
from datetime import date, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import audit as AU  # noqa: E402

SAMPLE = ROOT / "data" / "sample"
AUDIT = ROOT / "data" / "audit"
OUT = ROOT / "reports" / "quality_audit.md"


def load() -> AU.AuditData:
    return AU.load(AUDIT, SAMPLE)


def prepare(t: AU.AuditData | None = None) -> dict:
    """Everything the report and the page show (scorecard.audit.page_data)."""
    return AU.page_data(t or load(), SAMPLE)


def _d(s: str) -> str:
    return s[:16].replace("T", " ") if s else ""


def markdown(f: dict) -> str:
    w, ru = f["window"], f["rule"]
    out = ["# Quality audit", "",
           f"Site AUS-1 (synthetic), {w['start'][:10]} to {w['end'][:10]}. Generated by `scripts/render_audit.py` from `data/audit/` and "
           "the month's records; do not edit by hand.", "",
           f"The contract's audit clause: {ru['text']}", "",
           f"Sample drawn {_d(f['drawn_at'])} UTC with the published seed {f['seed']} (reproduce it: `python scripts/render_audit.py --sample "
           f"{f['seed']}`). The RMA cage was scanned at {_d(f['cage_scanned_at'])} UTC, before the first walk-down.", "",
           "## Result", "", "| Partner | Closed records | Sampled | Records with an engine finding | Workmanship passed | Target | Findings |",
           "|---|---:|---:|---:|---:|---:|---:|"]
    for s in f["summary"].values():
        out.append(f"| {s['name']} | {s['pool']} | {s['sampled']} | {s['engine']} | {s['passed']} of {s['sampled']} ({s['pass_pct']:g}%, "
                   f"{'met' if s['met'] else 'missed'}) | {ru['target_pct']}% | {s['findings']} |")
    out += ["", "A record passes workmanship when every checklist item that applies to it passes. Records with an engine finding already "
            "count toward that partner's record integrity measure; the audit shows them beside the walk-down.", "", "## Sampled records", "",
            "| Record | Partner | What | Closed | Engine findings | Checks | Workmanship |", "|---|---|---|---|---|---:|---|"]
    for x in f["records"]:
        eng = ", ".join(e["id"] for e in x["engine"]) or "none"
        out.append(f"| {x['id']} | {AU.PARTNERS[x['partner']]} | {x['what']} | {_d(x['closed'])} | {eng} | {len(x['items'])} | "
                   f"{'passed' if x['passed'] else 'failed'} |")
    out += ["", "## Findings", ""]
    for x in f["findings"]:
        out += [f"### {x['id']}: {x['title']}", "", f"{x['record']} ({x['owner']}), walked down {_d(x['at'])} UTC. {x['note']}"
                + (f" Records say: {x['expected']}." if x["expected"] else ""), "",
                f"Corrective action, due {x['due']}: {x['action']}", ""]
    if not f["findings"]:
        out += ["None.", ""]
    out += ["A finding means the work in place and the records do not reconcile. It starts a corrective action under the contract's "
            "corrective action plan requirements; it is not by itself a judgment of anyone.", "",
            "## Engine measures for every repair", "", "| ID | Measure | Target | Measured | Basis |", "|---|---|---|---|---|"]
    for q in f["quality"]:
        out.append(f"| {q['id']} | {q['name']} | {q['target']} | {q['measured']} | {q['basis']} |")
    out += ["", "## Agreements", "", "| Check | What agrees | Cases | Explained by a finding |", "|---|---|---:|---:|"]
    for a in f["agreements"]:
        out.append(f"| {a['name']} | {a['title']} | {a['checked'] - a['misses']:,} of {a['checked']:,} | {a['explained']:,} |")
    return "\n".join(out) + "\n"


def robustness_month(k: int) -> dict:
    from scorecard.sla_model import load_sla
    from scorecard.synthetic import SiteGenerator, write_dataset
    from scorecard.synthetic.audit import AuditLayer, write_audit
    syn = yaml.safe_load((ROOT / "config" / "synthetic.yaml").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp)
        write_dataset(SiteGenerator(load_sla(), syn, start=date(2025, 1, 6) + timedelta(weeks=4 * k), seed=2000 + k).run(), d)
        al = AuditLayer(d, 2000 + k)
        write_audit(al, al.run(), d / "audit")
        t = AU.load(d / "audit", d)
        r = AU.analyse(t, AU.run_engines(d))
        sc = AU.score(r["findings"], json.loads((d / "audit" / "answer_key.json").read_text(encoding="utf-8")))
    unexplained = {c.name: [c.checked - len(c.misses) + r["explained"].get(c.name, 0), c.checked, c.misses[:3]] for c in r["agreements"]}
    return {"month": k, "agreements": unexplained, "score": sc, "records": len(r["records"]),
            "corroborated": sum(s["corroborated"] for s in r["summary"].values())}


def robustness(n: int, jobs: int = 1) -> int:
    from concurrent.futures import ProcessPoolExecutor
    t0 = time.time()
    if jobs > 1:
        with ProcessPoolExecutor(jobs) as ex:
            res = list(ex.map(robustness_month, range(n)))
    else:
        res = [robustness_month(k) for k in range(n)]
    tot: dict[str, list[int]] = {}
    sc = {"planted": 0, "found": 0, "false_positives": 0}
    for r in res:
        for name, (a, b, misses) in r["agreements"].items():
            x = tot.setdefault(name, [0, 0])
            x[0], x[1] = x[0] + a, x[1] + b
            if a != b:
                for m in misses:
                    print(f"  month {r['month']}: {name}: {m}")
        for key in sc:
            sc[key] += r["score"][key]
        if r["score"]["false_positives"] or r["score"]["found"] < r["score"]["planted"]:
            print(f"  month {r['month']}: {r['score']}")
    print(f"Quality audit agreements on {n} generated months ({time.time() - t0:.0f} s; {sum(r['records'] for r in res)} sampled records, "
          f"{sum(r['corroborated'] for r in res)} engine findings corroborated by a walk-down):")
    for name, (a, b) in tot.items():
        print(f"  {name:<11} {a:,}/{b:,} (agree, or explained by a finding)")
    print(f"Quality audit findings on {n} generated months: {sc['found']} of {sc['planted']} planted found, {sc['false_positives']} false positives")
    ok = all(a == b for a, b in tot.values()) and sc["found"] == sc["planted"] and sc["false_positives"] == 0
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--sample", type=int, metavar="SEED", help="print the records this seed draws from the sample month")
    ap.add_argument("--robustness", type=int, metavar="N")
    ap.add_argument("--jobs", type=int, default=1)
    args = ap.parse_args()
    if args.robustness:
        return robustness(args.robustness, args.jobs)
    if args.sample is not None:
        m, ru = AU.load_month(SAMPLE), AU.rule()
        for p, pool in AU.pools(m).items():
            print(f"{AU.PARTNERS[p]} ({len(pool)} closed, {AU.sample_size(len(pool), ru)} drawn): " + ", ".join(AU.draw(pool, args.sample, p, ru)))
        return 0
    f = prepare()
    text = markdown(f)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/render_audit.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    sc = AU.score(f["findings"], json.loads((AUDIT / "answer_key.json").read_text(encoding="utf-8")))
    ok = sum(a["checked"] - a["misses"] + a["explained"] for a in f["agreements"])
    s = f["summary"]
    print(f"Quality audit: {sum(x['sampled'] for x in s.values())} records sampled (seed {f['seed']}); workmanship IT Partner "
          f"{s['it']['passed']} of {s['it']['sampled']}, Landlord {s['landlord']['passed']} of {s['landlord']['sampled']} (target "
          f"{f['rule']['target_pct']}%); {len(f['agreements'])} agreements, {ok} of {sum(a['checked'] for a in f['agreements'])} cases agree or "
          f"are explained; {len(f['findings'])} findings, {sc['found']} of {sc['planted']} planted, {sc['false_positives']} false positives")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
