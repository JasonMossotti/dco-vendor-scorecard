#!/usr/bin/env python3
"""Reconcile fire protection impairments: findings, agreements, and the report (reports/fire_protection.md).

Usage:
    python scripts/render_fire.py                  # write reports/fire_protection.md
    python scripts/render_fire.py --check          # fail if the report is stale
    python scripts/render_fire.py --robustness 60  # generate 60 months and score them (planted found, false positives)

The Telemetry page's Fire protection view (#fire) is built from prepare() by scripts/render_telemetry.py.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
from datetime import date, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import fire as F  # noqa: E402
from scorecard.synthetic.fire import iso  # noqa: E402

SAMPLE = ROOT / "data" / "sample"
FIRE = ROOT / "data" / "fire"
OUT = ROOT / "reports" / "fire_protection.md"
PLANTED_KINDS = ("restored_late", "unlogged")


def load() -> F.FireData:
    return F.load(FIRE, SAMPLE)


def prepare(t: F.FireData | None = None) -> dict:
    """Everything the report and the page show."""
    t = t or load()
    r = F.analyse(t)
    rc = r["rc"]
    imps = []
    for x in rc["imps"]:
        row = dict(x["row"])
        row["devices"] = x["devices"]
        row["panel_end"] = iso(x["panel_end"]) if x["panel_end"] else ""
        row["notices"] = [n["notice_id"] for n in x["notices"]]
        imps.append(row)
    oos = [{"device": s["device"], "point": s["point"], "signal": s["signal"], "start": iso(s["start"]), "end": iso(s["end"]),
            "text": s["text"], "logged": next((x["row"]["imp_id"] for x in rc["imps"] if s in x["spans"]), "")} for s in rc["spans"]]
    return {"window": t.manifest["window"], "findings": r["findings"],
            "agreements": [{"name": c.name, "title": c.title, "checked": c.checked, "misses": len(c.misses),
                            "explained": r["explained"].get(c.name, 0)} for c in r["agreements"]],
            "impairments": imps, "notices": t.notices, "panel": t.panel, "spans": oos,
            "rules": {"notice_h": F.NOTICE_LEAD_H, "watch_h": F.WATCH_AFTER_H, "log_min": F.LOG_AFTER_MIN}}


def markdown(f: dict) -> str:
    w = f["window"]
    imps = f["impairments"]
    planned = sum(1 for i in imps if i["type"] == "planned")
    out = ["# Fire protection impairments", "",
           f"Site AUS-1 (synthetic), {w['start'][:10]} to {w['end'][:10]}. Generated by `scripts/render_fire.py` from `data/fire/` and "
           "the month's VESDA events and maintenance records; do not edit by hand.", "",
           f"The fire panel's history ({len(f['panel'])} signals), the Landlord's impairment log ({len(imps)} impairments: {planned} planned, "
           f"{len(imps) - planned} unplanned), and the Customer's record of impairment notices ({len(f['notices'])}), reconciled under "
           "Interface Agreement section 12 (FPI-1 to FPI-6). The panel is the record of when protection was out.", "",
           "## Impairments", "", "| Impairment | Type | Devices | Reason | Start | Window end | Logged restored | Panel restored | Fire watch |",
           "|---|---|---|---|---|---|---|---|---|"]
    for i in imps:
        fw = f"{i['fire_watch_start'][11:16]} to {i['fire_watch_end'][11:16]}" if i["fire_watch_start"] else ""
        out.append(f"| {i['imp_id']} | {i['type']} | {', '.join(i['devices'])} | {i['reason']} | {i['start'][:16].replace('T', ' ')} | "
                   f"{i['window_end'][:16].replace('T', ' ')} | {i['restored_at'][:16].replace('T', ' ')} | {i['panel_end'][:16].replace('T', ' ')} | {fw} |")
    out += ["", "## Findings", ""]
    for x in f["findings"]:
        out += [f"### {x['id']}: {x['title']}", "", x["summary"], "", f"Owner: {x['owner']}. Contract: {x['contract']}.", ""]
        out += [f"- {ln}" for ln in x["lines"]] + [""]
    out += ["## Agreements", "", "| Check | What agrees | Cases | Explained by a finding |", "|---|---|---:|---:|"]
    for a in f["agreements"]:
        out.append(f"| {a['name']} | {a['title']} | {a['checked'] - a['misses']:,} of {a['checked']:,} | {a['explained']:,} |")
    return "\n".join(out) + "\n"


def robustness_month(k: int) -> dict:
    from scorecard.sla_model import load_sla
    from scorecard.synthetic import SiteGenerator, write_dataset
    from scorecard.synthetic.fire import FireLayer, write_fire
    syn = yaml.safe_load((ROOT / "config" / "synthetic.yaml").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp)
        write_dataset(SiteGenerator(load_sla(), syn, start=date(2025, 1, 6) + timedelta(weeks=4 * k), seed=2000 + k).run(), d)
        fl = FireLayer(d, 2000 + k)
        write_fire(fl, fl.run(), d / "fire")
        t = F.load(d / "fire", d)
        r = F.analyse(t)
        sc = F.score(r["findings"], json.loads((d / "fire" / "answer_key.json").read_text(encoding="utf-8")))
    return {"month": k, "agreements": {c.name: [c.checked - len(c.misses), c.checked, c.misses[:3]] for c in r["agreements"]},
            "score": sc, "false_positives": [f"{f['kind']}: {f['title']}" for f in r["findings"] if f["kind"] not in PLANTED_KINDS][:5],
            "impairments": len(t.imps)}


def robustness(n: int, jobs: int = 1) -> int:
    from concurrent.futures import ProcessPoolExecutor
    t0 = time.time()
    if jobs > 1:
        with ProcessPoolExecutor(jobs) as ex:
            res = list(ex.map(robustness_month, range(n)))
    else:
        res = [robustness_month(k) for k in range(n)]
    tot: dict[str, list[int]] = {}
    sc = {"planted": 0, "found": 0, "false_positives": 0}
    for r in res:
        for name, (a, b, misses) in r["agreements"].items():
            x = tot.setdefault(name, [0, 0])
            x[0], x[1] = x[0] + a, x[1] + b
            for m in misses:
                print(f"  month {r['month']}: {name}: {m}")
        for key in sc:
            sc[key] += r["score"][key]
        for fp in r["false_positives"]:
            print(f"  month {r['month']}: {fp}")
    print(f"Fire protection agreements on {n} generated months ({time.time() - t0:.0f} s; {sum(r['impairments'] for r in res)} impairments):")
    for name, (a, b) in tot.items():
        print(f"  {name:<15} {a:,}/{b:,}")
    print(f"Fire protection findings on {n} generated months: {sc['found']} of {sc['planted']} planted found, {sc['false_positives']} false positives")
    ok = all(a == b for a, b in tot.values()) and sc["found"] == sc["planted"] and sc["false_positives"] == 0
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--robustness", type=int, metavar="N")
    ap.add_argument("--jobs", type=int, default=1)
    args = ap.parse_args()
    if args.robustness:
        return robustness(args.robustness, args.jobs)
    f = prepare()
    text = markdown(f)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/render_fire.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    ok = sum(a["checked"] - a["misses"] for a in f["agreements"])
    sc = F.score(f["findings"], json.loads((FIRE / "answer_key.json").read_text(encoding="utf-8")))
    print(f"Fire protection: {len(f['impairments'])} impairments, {len(f['panel'])} panel signals, {len(f['agreements'])} agreements, "
          f"{ok:,} of {sum(a['checked'] for a in f['agreements']):,} cases agree; {len(f['findings'])} findings, {sc['found']} of "
          f"{sc['planted']} planted, {sc['false_positives']} false positives")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
