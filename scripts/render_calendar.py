#!/usr/bin/env python3
"""The maintenance and change calendar: conflicts, agreements, and the report (reports/change_calendar.md).

Usage:
    python scripts/render_calendar.py                  # write reports/change_calendar.md
    python scripts/render_calendar.py --check          # fail if the report is stale
    python scripts/render_calendar.py --robustness 60  # generate 60 forward schedules and score them

The Operations page's Calendar view (/ops/#calendar) is built from prepare() by scripts/render_ops.py.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import change_calendar as CC  # noqa: E402
from scorecard.synthetic.change_calendar import ForwardSchedule  # noqa: E402

LAYER = ROOT / "data" / "calendar"
OUT = ROOT / "reports" / "change_calendar.md"


def prepare() -> dict:
    """Everything the report and the page show (scorecard.change_calendar.page_data)."""
    return CC.page_data()


def _t(iso: str) -> str:
    """A UTC time as Central time, the way the page shows it."""
    if not iso:
        return ""
    lt = CC.local(CC.parse(iso))
    zone = "CDT" if CC.utc_offset(CC.parse(iso)).total_seconds() == -5 * 3600 else "CST"
    return f"{lt:%Y-%m-%d %H:%M} {zone}"


def markdown(f: dict) -> str:
    s = f["summary"]
    out = ["# Maintenance and change calendar", "",
           f"Site AUS-1 (synthetic), {f['days'][0]} to {f['first_compute']} (Hall C first compute). Generated by "
           "`scripts/render_calendar.py` from the records and `data/calendar/`; do not edit by hand. Times are Central.", "",
           "Every booked job on one calendar: the Customer CAB's changes, the Landlord's MOPs, the change-approval queue, the "
           "Landlord's preventive maintenance, the Hall B deployment milestones, and the Hall C commissioning scripts. The data "
           f"weeks ({f['days'][0]} to {f['days'][f['past_days'] - 1]}) come from the records as they are, and conflicts there are "
           f"reported as found. The forward look ({f['as_of']} to {f['first_compute']}) is the forward schedule.", "",
           "## Result", "", "| Period | Jobs | Overlap | Both feeds | Surge day | Freeze | Overran its window |", "|---|---:|---:|---:|---:|---:|---:|"]
    for per, name in (("past", "Data weeks"), ("forward", "Forward look")):
        k = s[per]["by_kind"]
        out.append(f"| {name} | {s[per]['jobs']} | {k['overlap']} | {k['both_feeds']} | {k['surge']} | {k['freeze']} | {k['overrun']} |")
    out += ["", f"Surge days (two or more Hall B energizations): {', '.join(f'{d} ({n})' for d, n in f['surge'].items())}.",
            f"First-compute freeze: {f['freeze'][0]} to {f['freeze'][1]}.", "", "## Findings", "",
            "A finding means the bookings do not reconcile with each other or with what the devices recorded; it starts a planning "
            "action, not a judgment of anyone.", "", "| ID | Period | Kind | Jobs | When | Owner | What |", "|---|---|---|---|---|---|---|"]
    for x in f["findings"]:
        out.append(f"| {x['id']} | {'Data weeks' if x['period'] == 'past' else 'Forward'} | {x['title']} | {', '.join(x['jobs'])} | "
                   f"{_t(x['at'])} | {', '.join(x['owners'])} | {x['text']} |")
    out += ["", "Each finding's action:", ""]
    for k, t in CC.ACTIONS.items():
        if any(x["kind"] == k for x in f["findings"]):
            out.append(f"- **{CC.KINDS[k]}.** {t}")
    out += ["", "## Agreements (data weeks)", "", "| Agreement | Cases | Agree | Explained by a finding |", "|---|---:|---:|---:|"]
    for a in f["agreements"]:
        out.append(f"| {a['title']} | {a['checked']} | {a['checked'] - len(a['misses'])} | {a['explained']} |")
    out += ["", "## Jobs that take a unit out", "", "| Job | Source | Status | Takes out | Group | Window |", "|---|---|---|---|---|---|"]
    for j in f["jobs"]:
        if j["takes"] == "none":
            continue
        g = f["groups"].get(j["group"]) if j["group"] else None
        what = f"pump 2 of {j['group'][6:]}" if j["takes"] == "pump" else f"feed {j['unit'][-1]} of rack {j['rack']}" if j["takes"] == "feed" else j["unit"]
        grp = f"{g['name']}{' (' + g['hall'].replace('HALL-', 'Hall ') + ')' if g['hall'] else ''}, {g['scheme']}" if g else "Rack feeds, 2N"
        out.append(f"| {j['id']} | {f['sources'][j['source']]} | {j['status']} | {what} | {grp} | {_t(j['start'])} to {_t(j['end'])[11:]} |")
    out += ["", "## How it works", "",
            "- **Effect of a job.** Read from its title (`config/calendar.yaml`, work_types): a CDU filter change isolates one of "
            "the CDU's two pumps, a UPS maintenance puts the UPS on maintenance bypass, a chiller maintenance locks the chiller "
            "out, a tap-off retorque opens one feed of the rack. A new rack's tap-off, a detector test, a generator exercise, and "
            "a firmware change on one rack take nothing out of a redundancy group. Where the change layer has an impact "
            "declaration, the calendar's effect must equal it.",
            "- **Groups.** The redundancy groups Site health uses (`src/scorecard/site_health.py`), from the site model and the "
            "device lists. Each CDU's two pumps are their own group; rack feeds are checked rack by rack.",
            f"- **Surge day.** A day with {f['surge_min']} or more Hall B energizations: Interface Agreement HO-4 tap-off "
            "energizations and rack power-ons from both partners' Jira (R-HO4, R-M4), done dates for done steps and due dates "
            "for the rest.",
            f"- **Freeze.** The {f['freeze_days']} days before Hall C first compute: no work that takes a unit out of a site-wide group "
            "(utility, generators, chillers, facility water pumps) and no Hall C work outside the commissioning plan.",
            "- **Windows.** A MOP or CAB change uses its approved window; a maintenance record without a MOP uses what the device "
            "recorded (the chiller's lockout in the BMS, the engine's run in the EMCP record) or the task's length before its "
            "recorded completion. A deferred change is shown but is off the calendar for the checks.",
            "- **Forward schedule.** Placed by the planner's own rules (one job at a time in each group, never both feeds of a "
            "rack, nothing on a surge day or in the freeze that the rules forbid), then one planted conflict of each kind. The "
            "checks never read the answer key. `python scripts/render_calendar.py --robustness 60` scores 60 schedules.", ""]
    return "\n".join(out)


def robustness(n: int) -> int:
    t0 = time.time()
    tot = {"planted": 0, "found": 0, "false_positives": 0}
    by_kind: dict[str, list[int]] = {}
    for k in range(n):
        out = ForwardSchedule(2000 + k).run()
        r = CC.analyse(schedule=out["schedule"])
        sc = CC.score(r["findings"], out["key"])
        for key in tot:
            tot[key] += sc[key]
        for p in out["key"]:
            hit = any(f["kind"] == p["kind"] and p["job"] in f["jobs"] for f in r["findings"] if f["period"] == "forward")
            by_kind.setdefault(p["kind"], [0, 0])[0] += hit
            by_kind[p["kind"]][1] += 1
        if sc["found"] != sc["planted"] or sc["false_positives"]:
            print(f"  schedule {2000 + k}: {sc}")
    print(f"Robustness, {n} forward schedules: planted {tot['found']}/{tot['planted']} found, {tot['false_positives']} false positives "
          f"({', '.join(f'{k} {a}/{b}' for k, (a, b) in sorted(by_kind.items()))}) in {time.time() - t0:.0f} s")
    return 0 if tot["found"] == tot["planted"] and not tot["false_positives"] else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--robustness", type=int, metavar="N")
    args = ap.parse_args()
    if args.robustness:
        return robustness(args.robustness)
    f = prepare()
    text = markdown(f)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/render_calendar.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    sc = CC.score(CC.analyse()["findings"], json.loads((LAYER / "answer_key.json").read_text(encoding="utf-8")))
    s = f["summary"]
    ok = sum(a["checked"] - len(a["misses"]) + a["explained"] for a in f["agreements"])
    print(f"Change calendar: {s['past']['jobs']} jobs in the data weeks ({s['past']['findings']} findings as found), {s['forward']['jobs']} "
          f"forward ({s['forward']['findings']} findings, {sc['found']} of {sc['planted']} planted, {sc['false_positives']} false positives); "
          f"{len(f['agreements'])} agreements, {ok} of {sum(a['checked'] for a in f['agreements'])} cases agree or are explained")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
