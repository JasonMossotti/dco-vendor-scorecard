#!/usr/bin/env python3
"""Reconcile the asset register: findings, corroborations, agreements, and the report (reports/asset_register.md).

Usage:
    python scripts/render_assets.py                  # write reports/asset_register.md
    python scripts/render_assets.py --check          # fail if the report is stale
    python scripts/render_assets.py --robustness 60  # generate 60 months and score them (planted found, false positives)

The register's view on the Devices tab (#assets) is built from prepare() by scripts/render_devices.py.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
from datetime import date, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scorecard import assets as A  # noqa: E402

SAMPLE = ROOT / "data" / "sample"
SECURITY = ROOT / "data" / "security"
MGMT = ROOT / "data" / "telemetry" / "mgmt"
STORAGE = ROOT / "data" / "telemetry" / "storage"
ASSETS = ROOT / "data" / "assets"
OUT = ROOT / "reports" / "asset_register.md"
STATUS_ORDER = ["installed", "received", "in_stock", "removed", "at_oem", "in_custody", "destroyed", "disposed"]


def load() -> A.AssetData:
    return A.load(ASSETS, SAMPLE, SECURITY, MGMT, STORAGE, known=A.known_findings(SAMPLE, SECURITY, STORAGE, MGMT))


def prepare(t: A.AssetData | None = None) -> dict:
    """Everything the report and the page show."""
    t = t or load()
    r = A.analyse(t)
    R = r["R"]
    st = R.state(t.end)[0]
    by_class: dict[str, dict[str, int]] = {}
    for tag, (s, _) in st.items():
        c = by_class.setdefault(R.asset[tag]["class"], {})
        c[s] = c.get(s, 0) + 1
    D = r["D"]
    rows = []
    for tag in sorted(R.asset):
        a = R.asset[tag]
        s, loc = st.get(tag, (None, ""))
        rows.append([tag, a["class"], a["serial"], s, loc, a["maintainer"]])
    hist = {}
    for x in t.tx:
        hist.setdefault(x["tag"], []).append([x["at"], x["action"], x["location"], x["ref"], x["by"]])
    reported = {slot: [D.source[slot], D.serial(slot, t.end)] for slot in sorted(D.base)}
    cases = {c.name: [c.checked, c.checked - len(c.misses)] for c in r["agreements"]}
    return {"window": t.manifest["window"], "findings": r["findings"], "corroborations": r["corroborations"],
            "agreements": [{"name": c.name, "title": c.title, "checked": c.checked, "misses": len(c.misses),
                            "explained": r["explained"].get(c.name, 0)} for c in r["agreements"]],
            "by_class": by_class, "statuses": STATUS_ORDER, "assets": rows, "opening": {a["tag"]: [a["since"], a["status"], a["location"], a["ref"]] for a in t.opening},
            "history": hist, "reported": reported, "portal": t.portal, "disposals": t.disposals, "cases": cases,
            "total": len(rows), "transactions": len(t.tx)}


def markdown(f: dict) -> str:
    w = f["window"]
    out = ["# Asset register reconciliation", "",
           f"Site AUS-1 (synthetic), {w['start'][:10]} to {w['end'][:10]}. Generated by `scripts/render_assets.py` from `data/assets/` and the "
           "records it is reconciled against; do not edit by hand.", "",
           f"{f['total']:,} assets in the register, {f['transactions']:,} transactions this month. Interface Agreement section 11 "
           "(REG-1 to REG-6).", "", "## Assets at month end", "",
           "| Class | " + " | ".join(s.replace("_", " ") for s in f["statuses"]) + " |", "|---|" + "---:|" * len(f["statuses"])]
    for c in sorted(f["by_class"]):
        out.append(f"| {c} | " + " | ".join(f"{f['by_class'][c].get(s, 0):,}" for s in f["statuses"]) + " |")
    out += ["", "## Findings", ""]
    for x in f["findings"]:
        out += [f"### {x['id']}: {x['title']}", "", x["summary"], "", f"Owner: {x['owner']}. Contract: {x['contract']}.", ""]
        out += [f"- {ln}" for ln in x["lines"]] + [""]
    out += ["## Corroborations", "", "Disagreements another check already found; the register shows them too, and they are not counted again.", "",
            "| Finding | Type | What the register saw |", "|---|---|---|"]
    for c in f["corroborations"]:
        out.append(f"| {c['finding']} ({c['source']}) | {c['type']} | {c['text']} |")
    out += ["", "## Agreements", "", "| Check | What agrees | Cases | Explained by a finding |", "|---|---|---:|---:|"]
    for a in f["agreements"]:
        out.append(f"| {a['name']} | {a['title']} | {a['checked'] - a['misses']:,} of {a['checked']:,} | {a['explained']:,} |")
    return "\n".join(out) + "\n"


def robustness_month(k: int) -> dict:
    from scorecard.sla_model import load_sla
    from scorecard.synthetic import SiteGenerator, write_dataset
    from scorecard.synthetic.assets import AssetLayer, write_assets
    from scorecard.synthetic.security import generate as gen_security
    from scorecard.synthetic.telemetry_mgmt import MgmtTelemetry, write_mgmt
    from scorecard.synthetic.telemetry_storage import StorageTelemetry, write_storage
    syn = yaml.safe_load((ROOT / "config" / "synthetic.yaml").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp)
        write_dataset(SiteGenerator(load_sla(), syn, start=date(2025, 1, 6) + timedelta(weeks=4 * k), seed=2000 + k).run(), d)
        gen_security(d, d / "security")
        mg = MgmtTelemetry(d, 2000 + k)
        write_mgmt(mg, mg.run(), d / "mgmt")
        sg = StorageTelemetry(d, 2000 + k, d / "mgmt")
        write_storage(sg, sg.run(), d / "storage")
        al = AssetLayer(d, 2000 + k, d / "security", d / "mgmt", d / "storage")
        write_assets(al, al.run(), d / "assets")
        t = A.load(d / "assets", d, d / "security", d / "mgmt", d / "storage", known=A.known_findings(d, d / "security", d / "storage", d / "mgmt"))
        r = A.analyse(t)
        sc = A.score(r["findings"], json.loads((d / "assets" / "answer_key.json").read_text(encoding="utf-8")))
    return {"month": k, "agreements": {c.name: [c.checked - len(c.misses), c.checked, c.misses[:3]] for c in r["agreements"]},
            "score": sc, "false_positives": [f"{f['kind']}: {f['title']}" for f in r["findings"]
                                             if f["kind"] not in ("live_in_stock", "rma_not_received", "disposed_answering")][:5],
            "corroborations": len(r["corroborations"])}


def robustness(n: int, jobs: int = 1) -> int:
    from concurrent.futures import ProcessPoolExecutor
    t0 = time.time()
    if jobs > 1:
        with ProcessPoolExecutor(jobs) as ex:
            res = list(ex.map(robustness_month, range(n)))
    else:
        res = [robustness_month(k) for k in range(n)]
    tot: dict[str, list[int]] = {}
    sc = {"planted": 0, "found": 0, "false_positives": 0}
    for r in res:
        for name, (a, b, misses) in r["agreements"].items():
            x = tot.setdefault(name, [0, 0])
            x[0], x[1] = x[0] + a, x[1] + b
            for m in misses:
                print(f"  month {r['month']}: {name}: {m}")
        for key in sc:
            sc[key] += r["score"][key]
        for fp in r["false_positives"]:
            print(f"  month {r['month']}: {fp}")
    print(f"Asset register agreements on {n} generated months ({time.time() - t0:.0f} s):")
    for name, (a, b) in tot.items():
        print(f"  {name:<10} {a:,}/{b:,}")
    print(f"Asset register findings on {n} generated months: {sc['found']} of {sc['planted']} planted found, "
          f"{sc['false_positives']} false positives; {sum(r['corroborations'] for r in res)} corroborations of other checks' findings")
    ok = all(a == b for a, b in tot.values()) and sc["found"] == sc["planted"] and sc["false_positives"] == 0
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--robustness", type=int, metavar="N")
    ap.add_argument("--jobs", type=int, default=1)
    args = ap.parse_args()
    if args.robustness:
        return robustness(args.robustness, args.jobs)
    f = prepare()
    text = markdown(f)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/render_assets.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    ok = sum(a["checked"] - a["misses"] for a in f["agreements"])
    key = json.loads((ASSETS / "answer_key.json").read_text(encoding="utf-8"))
    sc = A.score(f["findings"], key)
    print(f"Asset register: {f['total']:,} assets, {len(f['agreements'])} agreements, {ok:,} of {sum(a['checked'] for a in f['agreements']):,} "
          f"cases agree; {len(f['findings'])} findings, {sc['found']} of {sc['planted']} planted, {sc['false_positives']} false positives; "
          f"{len(f['corroborations'])} corroborations")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
